def cpp_header(i):
    lines = [f"// Generated by tools/bench_scale.py: module {i}.", "#pragma once",
             "#include <cstdint>", "#include <string>", "#include <vector>",
             "#include <unordered_map>"]
    lines += [f'#include "m{d:03}.h"' for d in deps_of(i)]
    lines.append("")
    for k in range(STRUCTS):
        p = f"Part{i}_{k}"
        lines += f"""struct {p} {{
    int64_t id = 0;
    int64_t weight = 0;
    std::string label;
    std::vector<int64_t> tags;

    explicit {p}(int64_t id);
    int64_t score() const;
    void grow(int64_t by);
    int64_t mix(const {p}& other) const;
    bool operator==(const {p}& rhs) const {{ return id == rhs.id && weight == rhs.weight; }}
    bool operator<(const {p}& rhs) const {{
        return weight != rhs.weight ? weight < rhs.weight : id < rhs.id;
    }}
    bool operator>(const {p}& rhs) const {{ return rhs < *this; }}
}};
""".splitlines()
    lines += f"""template <typename T>
struct Shelf{i} {{
    std::vector<T> items;
    void put(T v) {{ items.push_back(std::move(v)); }}
    size_t count() const {{ return items.size(); }}
}};

template <typename T>
size_t largest{i}(const std::vector<T>& xs) {{
    size_t best = 0;
    for (size_t j = 1; j < xs.size(); j++) {{
        if (xs[j] > xs[best]) best = j;
    }}
    return best;
}}

int64_t touch{i}(int64_t x);
int64_t run{i}(int64_t seed);
""".splitlines()
    return "\n".join(lines) + "\n"


def cpp_source(i, edit=0):
    lines = [f"// Generated by tools/bench_scale.py: module {i}.", f'#include "m{i:03}.h"', ""]
    for k in range(STRUCTS):
        a, b, c = consts(i, k)
        p = f"Part{i}_{k}"
        lines += f"""{p}::{p}(int64_t id) : id(id) {{
    weight = (id * {a} + {b}) % 1009;
    label = "p{i}_{k}_" + std::to_string(id);
    for (int64_t t = 0; t < {c}; t++) tags.push_back((id * {c} + t) % 97);
}}

int64_t {p}::score() const {{
    int64_t s = weight;
    for (int64_t t : tags) s = (s * 31 + t) % {MOD};
    return (s + (int64_t)label.size()) % {MOD};
}}

void {p}::grow(int64_t by) {{
    weight = (weight + by) % 1009;
    tags.push_back(by % 97);
}}

int64_t {p}::mix(const {p}& other) const {{
    if (*this > other) return (score() * 7 + other.score()) % {MOD};
    return (other.score() * 7 + score()) % {MOD};
}}
""".splitlines()
    lines += f"""enum class Mode{i} {{ Add, Mul, Keep }};

static Mode{i} mode{i}(int64_t x) {{
    if (x % 3 == 0) return Mode{i}::Add;
    if (x % 3 == 1) return Mode{i}::Mul;
    return Mode{i}::Keep;
}}

static int64_t apply{i}(Mode{i} m, int64_t acc, int64_t v) {{
    switch (m) {{
    case Mode{i}::Add: return (acc + v) % {MOD};
    case Mode{i}::Mul: return (acc * (v % 13 + 1)) % {MOD};
    case Mode{i}::Keep: return acc;
    }}
    return acc;
}}

int64_t touch{i}(int64_t x) {{
    {f"Part{i}_0"} p(x);
    return (p.score() + {edit}) % {MOD};
}}

int64_t run{i}(int64_t seed) {{
    int64_t acc = {i};
    std::unordered_map<int64_t, int64_t> index;""".splitlines()
    for k in range(STRUCTS):
        p = f"Part{i}_{k}"
        lines += f"""    Shelf{i}<{p}> shelf{k};
    for (int64_t j = 0; j < {ITEMS}; j++) {{
        {p} part(seed + j * {k + 1});
        part.grow(j);
        {p} first(seed);
        acc = apply{i}(mode{i}(j + {k}), acc, part.mix(first));
        index[part.id] = part.weight;
        shelf{k}.put(std::move(part));
    }}
    acc = (acc + (int64_t)largest{i}(shelf{k}.items) + (int64_t)shelf{k}.count()) % {MOD};""".splitlines()
    lines.append(f"    acc = (acc + (int64_t)index.size()) % {MOD};")
    for d in deps_of(i):
        lines.append(f"    acc = (acc + touch{d}(seed + {i})) % {MOD};")
    lines += ["    return acc;", "}", ""]
    return "\n".join(lines)


def write_cpp(n, root):
    root.mkdir(parents=True, exist_ok=True)
    for i in range(n):
        (root / f"m{i:03}.h").write_text(cpp_header(i))
        (root / f"m{i:03}.cpp").write_text(cpp_source(i))
    main = ["// Generated by tools/bench_scale.py: runs every module.", "#include <cstdio>"]
    main += [f'#include "m{i:03}.h"' for i in range(n)]
    main += ["", "int main() {", "    int64_t total = 0;"]
    main += [f"    total = (total + run{i}(7)) % {MOD};" for i in range(n)]
    main += ['    std::printf("checksum %lld\\n", (long long)total);', "    return 0;", "}", ""]
    (root / "main.cpp").write_text("\n".join(main))


def generate(n, root):
    if root.exists():
        shutil.rmtree(root)
    write_dazzle(n, root / "dazzle")
    write_cpp(n, root / "cpp")
    dz_lines = sum(len(p.read_text().splitlines()) for p in (root / "dazzle").rglob("*.dz"))
    cpp_lines = sum(len(p.read_text().splitlines()) for p in (root / "cpp").iterdir())
    return dz_lines, cpp_lines


# ---------------------------------------------------------------------------
# building and timing
# ---------------------------------------------------------------------------

CXX_FLAGS = ["-std=c++17", "-fno-exceptions", "-fno-rtti", "-Wall", "-Wextra", "-O0", "-g"]

# What `dz build --timings` reports that is not Dazzle's own work.
NOT_DAZZLE = {"C and C++ headers", "C and C++ libraries", "C++ compiler", "link", "total"}


def dz_build(dz, root, cxx):
    """One `dz build`: its wall time, and its phases in milliseconds."""
    started = time.perf_counter()
    out = subprocess.run([str(dz), "build", "--timings", "--cxx", cxx, str(root)],
                         capture_output=True, text=True)
    wall = time.perf_counter() - started
    if out.returncode != 0:
        sys.exit(f"dz build failed in {root}:\n{out.stdout}{out.stderr}")
    phases = {}
    for line in (out.stdout + out.stderr).splitlines():
        m = re.match(r"\s+(.+?)\s+([\d.]+) ms$", line)
        if m:
            phases[m.group(1)] = float(m.group(2))
    return wall, phases


def cpp_build(root, cxx):
    """The C++ half, built as `make -j` builds a plain project: each .cpp compiled on its own
    when it or a header it includes is newer than its object, as many at once as there are
    cores, then one link. Returns the wall time."""
    started = time.perf_counter()
    obj = root / "build"
    obj.mkdir(exist_ok=True)
    sources = sorted(root.glob("*.cpp"))
    stale = []
    for src in sources:
        o = obj / (src.stem + ".o")
        d = obj / (src.stem + ".d")
        if not o.exists() or not d.exists():
            stale.append(src)
            continue
        built = o.stat().st_mtime
        inputs = d.read_text().replace("\\\n", " ").split(":", 1)[1].split()
        if any(not Path(p).exists() or Path(p).stat().st_mtime > built for p in inputs):
            stale.append(src)
    cores = os.cpu_count() or 4
    running = []
    for src in stale:
        while len(running) >= cores:
            wait_one(running)
        cmd = [cxx, *CXX_FLAGS, "-c", str(src), "-o", str(obj / (src.stem + ".o")), "-MMD",
               "-MF", str(obj / (src.stem + ".d"))]
        running.append((src, subprocess.Popen(cmd, stderr=subprocess.PIPE, text=True)))
    while running:
        wait_one(running)
    binary = obj / exe("app")
    if stale or not binary.exists():
        link = [cxx, *CXX_FLAGS, *[str(obj / (s.stem + ".o")) for s in sources], "-o", str(binary)]
        out = subprocess.run(link, capture_output=True, text=True)
        if out.returncode != 0:
            sys.exit(f"the C++ link failed:\n{out.stderr}")
    return time.perf_counter() - started


def wait_one(running):
    src, proc = running.pop(0)
    _, err = proc.communicate()
    if proc.returncode != 0:
        sys.exit(f"{src} did not compile:\n{err}")


def edit(project, n, which, counter):
    """The one-line change: `touch`'s constant in module `which`, in both halves."""
    dz = project / "dazzle" / f"m{which:03}" / "src" / f"m{which:03}.dz"
    dz.write_text(dz_module(which, counter))
    (project / "cpp" / f"m{which:03}.cpp").write_text(cpp_source(which, counter))


def checksum(binary):
    out = subprocess.run([str(binary)], capture_output=True, text=True)
    line = [l for l in out.stdout.splitlines() if l.startswith("checksum")]
    if out.returncode != 0 or not line:
        sys.exit(f"{binary} did not print a checksum:\n{out.stdout}{out.stderr}")
    return line[0]


SCENARIOS = ["from clean", "nothing changed", "leaf module changed", "root module changed"]


def measure(dz, n, cxx, builds):
    """Every scenario for one size and one compiler: the median of `builds` of each."""
    project = OUT / str(n)
    lines = generate(n, project)
    dzroot, cpproot = project / "dazzle", project / "cpp"
    results = {"modules": n, "lines": {"dazzle": lines[0], "cpp": lines[1]}, "cxx": cxx}
    counter = [0]

    def scenario(name):
        dz_runs, cpp_runs = [], []
        for run in range(builds + 1):
            if name == "from clean":
                shutil.rmtree(dzroot / "build", ignore_errors=True)
                shutil.rmtree(cpproot / "build", ignore_errors=True)
            elif name != "nothing changed":
                counter[0] += 1
                edit(project, n, n - 1 if name.startswith("leaf") else 0, counter[0])
            d = dz_build(dz, dzroot, cxx)
            c = cpp_build(cpproot, cxx)
            # The first build of an edit scenario only brings the previous one up to date.
            if run > 0 or name == "from clean":
                dz_runs.append(d)
                cpp_runs.append(c)
        dz_runs = dz_runs[-builds:]
        cpp_runs = cpp_runs[-builds:]
        phases = {}
        for key in {k for _, p in dz_runs for k in p}:
            phases[key] = statistics.median(p.get(key, 0.0) for _, p in dz_runs)
        own = sum(v for k, v in phases.items() if k not in NOT_DAZZLE)
        return {
            "dazzle": statistics.median(w for w, _ in dz_runs),
            "cpp": statistics.median(cpp_runs),
            "dazzle_phases_ms": own,
            "cxx_ms": phases.get("C++ compiler", 0.0) + phases.get("link", 0.0),
            "phases": phases,
        }

    for name in SCENARIOS:
        results[name] = scenario(name)
    a = checksum(dzroot / "build" / "bin" / exe("app"))
    b = checksum(cpproot / "build" / exe("app"))
    if a != b:
        sys.exit(f"the halves disagree at {n} modules: Dazzle {a}, C++ {b}")
    results["checksum"] = a
    return results


def report(results, info):
    out = ["| Modules | Lines (Dazzle / C++) | Compiler | " + " | ".join(SCENARIOS) + " |",
           "|---:|---|---|" + "---:|" * len(SCENARIOS)]
    for r in results:
        cells = [f"{r[s]['dazzle']:.2f} s / {r[s]['cpp']:.2f} s" for s in SCENARIOS]
        out.append(f"| {r['modules']} | {r['lines']['dazzle']} / {r['lines']['cpp']} | "
                   f"{r['cxx']} | " + " | ".join(cells) + " |")
    out += ["", "Where Dazzle's time goes: its own phases / the C++ compiler and link.", "",
            "| Modules | Compiler | " + " | ".join(SCENARIOS) + " |",
            "|---:|---|" + "---:|" * len(SCENARIOS)]
    for r in results:
        cells = [f"{r[s]['dazzle_phases_ms'] / 1000:.2f} s / {r[s]['cxx_ms'] / 1000:.2f} s"
                 for s in SCENARIOS]
        out.append(f"| {r['modules']} | {r['cxx']} | " + " | ".join(cells) + " |")
    out += [
        "",
        "Each cell is Dazzle / C++, the median of the builds asked for, in debug (`-O0 -g`). "
        "Dazzle is `dz build`. C++ is the same program as one header and one source per "
        "module, built as `make -j` builds a plain project: each source compiled on its own "
        "when it or a header it includes is newer than its object, one per core at once, with "
        "no precompiled headers, then linked. From clean deletes both `build/` folders "
        "(Dazzle's per-user cache stays, as C++'s standard library stays built). A changed "
        "module has one function's body changed, which changes no header: the leaf is the "
        "last module, which no other calls, and the root is module 0, which every other "
        "depends on. Dazzle's own phases are everything `--timings` reports but the headers, "
        "the libraries, the C++ compiler and the link.",
        "",
        f"- CPU: {info['cpu']} ({info['cores']} threads)",
        f"- OS: {info['os']}",
    ]
    out += [f"- `{c}`: {v}" for c, v in info["compilers"].items()]
    out += [f"- `dz`: {info['dz']}", f"- Load average before / after: {info['load']}"]
    return "\n".join(out) + "\n"


def first_line(cmd):
    try:
        out = subprocess.run(cmd, capture_output=True, text=True)
    except OSError:
        return None
    text = (out.stdout or out.stderr).strip()
    return text.splitlines()[0] if text else None


def cpu_name():
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def load():
    try:
        return os.getloadavg()[0]
    except (AttributeError, OSError):
        return float("nan")


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "generate":
        if len(sys.argv) != 4:
            sys.exit("usage: bench_scale.py generate <modules> <dir>")
        print(generate(int(sys.argv[2]), Path(sys.argv[3])))
        return
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--sizes", default="10,25,50,100", help="module counts (default 10,25,50,100)")
    p.add_argument("--cxx", default="clang++,g++", help="comma-separated compilers")
    p.add_argument("--dz", default=None, help="the dz binary (default: target/release/dz)")
    p.add_argument("--builds", type=int, default=3, help="builds per scenario (default 3)")
    p.add_argument("--markdown", help="also write the report here")
    p.add_argument("--json", help="also write every measurement here")
    args = p.parse_args()
    dz = Path(args.dz) if args.dz else ROOT / "target" / "release" / exe("dz")
    if not dz.exists():
        sys.exit(f"{dz} not found: cargo build --release -p dz")
    compilers = [c for c in args.cxx.split(",") if shutil.which(c)]
    before = load()
    print(f"load average {before:.2f}", file=sys.stderr)
    results = []
    for n in (int(s) for s in args.sizes.split(",")):
        for cxx in compilers:
            print(f"{n} modules, {cxx} ...", file=sys.stderr)
            results.append(measure(dz, n, cxx, args.builds))
    info = {
        "cpu": cpu_name(),
        "cores": os.cpu_count(),
        "os": platform.platform(),
        "compilers": {c: first_line([c, "--version"]) for c in compilers},
        "dz": first_line(["git", "-C", str(ROOT), "log", "-1", "--format=commit %h"])
        if not args.dz else str(dz),
        "load": f"{before:.2f} / {load():.2f}",
    }
    text = report(results, info)
    print(text)
    if args.markdown:
        Path(args.markdown).write_text(text)
    if args.json:
        Path(args.json).write_text(json.dumps({"info": info, "results": results}, indent=2))


if __name__ == "__main__":
    main()
