#!/usr/bin/env python3
"""Build time at scale (T-0012): a generated project of N modules, Dazzle against C++.

The programs in tests/bench_programs are one file each, which is C++'s best case: one
compiler invocation and no build system. This generates a project of N modules with a
realistic shape, and the same program in C++, N translation units built the way a plain
CMake or Make project builds them: each .cpp compiled on its own, in parallel, with no
precompiled headers, then linked. Both print a `checksum` line and must agree.

Each module has a few structs with fields, a constructor and methods, `Eq` and `Ord` impls,
a generic container instantiated over every one of its structs, an enum with a `switch`, a
`HashMap`, and calls into two earlier modules. A module is about 400 lines of Dazzle.

For every size asked for, it times four builds of each half, debug, as someone works:

- from clean: `build/` deleted (Dazzle's per-user cache is kept, as C++'s standard library
  is already built);
- nothing changed;
- after a one-line change to a leaf module, one nobody depends on;
- after a one-line change to the root of the module graph, which every module depends on,
  without changing what it exports, so only its own file compiles again in C++.

    python tools/bench_scale.py                          # sizes 10, 25, 50, 100
    python tools/bench_scale.py --sizes 50 --cxx g++
    python tools/bench_scale.py generate 50 target/scale/50   # just write the projects
    python tools/bench_scale.py --dz path/to/dz --markdown out.md

Programs are written to target/scale/<N>/{dazzle,cpp}/.
"""

import argparse
import json
import os
import platform
import re
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "target" / "scale"

STRUCTS = 6  # structs per module
ITEMS = 8  # parts each module builds of each struct
MOD = 1000003  # every sum is kept below this, so no half can overflow


def exe(name):
    return name + ".exe" if os.name == "nt" else name


def deps_of(i):
    """The modules `i` calls into: the one before it, and the one at half its index. So the
    graph is deep and wide at once, and module 0 is under every other."""
    return sorted({d for d in (i - 1, i // 2) if 0 <= d < i})


def consts(i, k):
    """Per struct, so no two compute the same thing."""
    return 3 + (i * 7 + k * 13) % 29, 1 + (i * 11 + k * 5) % 101, 2 + (i + k * 3) % 17


# ---------------------------------------------------------------------------
# Dazzle
# ---------------------------------------------------------------------------


def dz_module(i, edit=0):
    lines = [f"// Generated by tools/bench_scale.py: module {i}.", ""]
    for k in range(STRUCTS):
        a, b, c = consts(i, k)
        p = f"Part{i}_{k}"
        lines += f"""/// One of module {i}'s parts: some fields, a list, and arithmetic over them.
pub struct {p} {{
    pub id:     i64 = 0
    pub weight: i64 = 0
    pub label:  String
    pub tags:   List<i64>

    {p}(id: i64) {{
        self.id = id
        weight = (id * {a} + {b}) % 1009
        label = format!("p{i}_{k}_{{}}", id)
        for t in 0..{c} {{
            tags.push((id * {c} + t as i64) % 97)
        }}
    }}

    /// A checksum of everything it holds.
    pub fn score(&self) -> i64 {{
        let mut s = weight
        for t in tags {{
            s = (s * 31 + t) % {MOD}
        }}
        return (s + label.len() as i64) % {MOD}
    }}

    /// Heavier by `by`, with one more tag.
    pub fn grow(&mut self, by: i64) kills self.tags@items {{
        weight = (weight + by) % 1009
        tags.push(by % 97)
    }}

    /// Its score and another's, the larger weighing more.
    pub fn mix(&self, other: &{p}) -> i64 {{
        if self > other {{
            return (self.score() * 7 + other.score()) % {MOD}
        }}
        return (other.score() * 7 + self.score()) % {MOD}
    }}
}}

impl Eq for {p} {{
    fn eq(&self, rhs: &{p}) -> bool {{
        return id == rhs.id && weight == rhs.weight
    }}
}}

impl Ord for {p} {{
    fn cmp(&self, rhs: &{p}) -> Ordering {{
        if weight < rhs.weight {{
            return .Less
        }}
        if weight > rhs.weight {{
            return .Greater
        }}
        if id < rhs.id {{
            return .Less
        }}
        if id > rhs.id {{
            return .Greater
        }}
        return .Equal
    }}
}}
""".splitlines() + [""]
    lines += f"""/// Holds parts of one kind: instantiated once for each of this module's structs.
pub struct Shelf{i}<T> {{
    pub items: List<T>

    pub fn put(&mut self, v: T) kills self.items@items {{
        items.push(move(v))
    }}

    pub fn count(&self) -> usize {{
        return items.len()
    }}
}}

/// Where the largest of `xs` is, the first of equals.
fn largest{i}<T: Ord>(xs: &List<T>) -> usize {{
    let mut best: usize = 0
    for j in 1..xs.len() {{
        if xs[j] > xs[best] {{
            best = j
        }}
    }}
    return best
}}

pub enum Mode{i} {{
    Add
    Mul
    Keep
}}

fn mode{i}(x: i64) -> Mode{i} {{
    if x % 3 == 0 {{
        return .Add
    }}
    if x % 3 == 1 {{
        return .Mul
    }}
    return .Keep
}}

fn apply{i}(m: Mode{i}, acc: i64, v: i64) -> i64 {{
    return switch m {{
        case Add {{ (acc + v) % {MOD} }}
        case Mul {{ (acc * (v % 13 + 1)) % {MOD} }}
        case Keep {{ acc }}
    }}
}}

/// One part's score, for the modules that depend on this one.
pub fn touch{i}(x: i64) -> i64 {{
    let p = Part{i}_0(x)
    return (p.score() + {edit}) % {MOD}
}}

/// This module's work: builds its parts, keeps them on shelves, and calls into the modules
/// it depends on.
pub fn run{i}(seed: i64) -> i64 {{
    let mut acc: i64 = {i}
    let mut index = HashMap<i64, i64>()""".splitlines()
    for k in range(STRUCTS):
        p = f"Part{i}_{k}"
        lines += f"""    let mut shelf{k} = Shelf{i}<{p}>{{ items: List<{p}>() }}
    for j in 0..{ITEMS} {{
        let mut part = {p}(seed + j as i64 * {k + 1})
        part.grow(j as i64)
        let first = {p}(seed)
        acc = apply{i}(mode{i}(j as i64 + {k}), acc, part.mix(&first))
        index.insert(part.id, part.weight)
        shelf{k}.put(move(part))
    }}
    acc = (acc + largest{i}(&shelf{k}.items) as i64 + shelf{k}.count() as i64) % {MOD}""".splitlines()
    lines.append(f"    acc = (acc + index.len() as i64) % {MOD}")
    for d in deps_of(i):
        lines.append(f"    acc = (acc + touch{d}(seed + {i})) % {MOD}")
    lines += ["    return acc", "}", ""]
    return "\n".join(lines)


def dz_manifest(name, deps):
    text = f'[module]\nname    = "{name}"\nsources = ["src/**/*.dz"]\n\n[dependencies]\nstd = {{ open = true }}\n'
    for d in deps:
        text += f'm{d:03} = {{ path = "{"../" if name != "app" else ""}m{d:03}", open = true }}\n'
    return text


def write_dazzle(n, root):
    for i in range(n):
        d = root / f"m{i:03}"
        (d / "src").mkdir(parents=True, exist_ok=True)
        (d / "dazzle.toml").write_text(dz_manifest(f"m{i:03}", deps_of(i)))
        (d / "src" / f"m{i:03}.dz").write_text(dz_module(i))
    (root / "src").mkdir(parents=True, exist_ok=True)
    (root / "dazzle.toml").write_text(dz_manifest("app", range(n)))
    body = ["// Generated by tools/bench_scale.py: runs every module.", "", "fn main() {",
            "    let mut total: i64 = 0"]
    body += [f"    total = (total + run{i}(7)) % {MOD}" for i in range(n)]
    body += ['    println!("checksum {}", total)', "}", ""]
    (root / "src" / "main.dz").write_text("\n".join(body))


