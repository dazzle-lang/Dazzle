//! An edit re-emits only the modules it can affect (T-0197): the others' generated C++ is
//! kept as the last build wrote it. `crates/dz/tests/incremental.rs` holds the result to a
//! clean build; this pins that something is in fact kept, and that `DZ_INCREMENTAL=verify`
//! would say if what was kept were wrong.
//!
//! The project is an app over a library. The library's generated `lib.cpp` is changed by
//! hand, keeping its size and time, so only whether it is emitted again can tell.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn project() -> PathBuf {
    let dir = std::env::temp_dir().join(format!("dz_reuse_{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    for d in ["src", "lib/src"] {
        std::fs::create_dir_all(dir.join(d)).unwrap();
    }
    std::fs::write(
        dir.join("dazzle.toml"),
        "[module]\nname = \"app\"\nsources = [\"src/**/*.dz\"]\n\n[dependencies]\n\
         std = { open = true }\nlib = { path = \"lib\", open = true }\n\n\
         [build]\noutput = \"executable\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("lib/dazzle.toml"),
        "[module]\nname = \"lib\"\nsources = [\"src/**/*.dz\"]\n\n[dependencies]\n\
         std = { open = true }\n",
    )
    .unwrap();
    // `unused` is a warning the library's ownership check gives, printed again for it while
    // it is not checked again.
    std::fs::write(
        dir.join("lib/src/lib.dz"),
        "pub fn twice(x: i32) -> i32 {\n    let unused = 1\n    return x * 2\n}\n",
    )
    .unwrap();
    write_main(&dir, 1);
    dir
}

fn write_main(dir: &Path, n: i32) {
    let text = format!("fn main() {{\n    println!(\"{{}}\", twice({n}))\n}}\n");
    std::fs::write(dir.join("src/main.dz"), text).unwrap();
}

fn dz(dir: &Path, incremental: Option<&str>) -> Output {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_dz"));
    cmd.args(["run"]).current_dir(dir);
    for name in ["DZ_INCREMENTAL", "DZ_REGIONS", "DZ_CXXFLAGS", "DZ_STAMP_IDENTITY"] {
        cmd.env_remove(name);
    }
    if let Some(v) = incremental {
        cmd.env("DZ_INCREMENTAL", v);
    }
    cmd.env("DZ_CACHE_DIR", std::env::temp_dir().join("dz_reuse_cache"));
    cmd.output().expect("failed to run dz")
}

/// `path` with one character changed and its size and time as they were.
fn tamper(path: &Path) {
    let time = std::fs::metadata(path).unwrap().modified().unwrap();
    let text = std::fs::read_to_string(path).unwrap();
    // A comment's letter, so the C++ still compiles.
    let changed = text.replacen("Generated by", "generated by", 1);
    assert_ne!(text, changed, "the file starts with its comment");
    std::fs::write(path, changed).unwrap();
    std::fs::File::options().write(true).open(path).unwrap().set_modified(time).unwrap();
}

#[test]
fn an_edit_keeps_the_modules_it_cannot_affect() {
    if Command::new("c++").arg("--version").output().is_err()
        && std::env::var_os("DZ_CXX").is_none()
    {
        eprintln!("skipping: no C++ compiler available");
        return;
    }
    let dir = project();
    let lib_cpp = dir.join("build/cpp/lib.cpp");
    let first = dz(&dir, None);
    assert!(first.status.success(), "{}", String::from_utf8_lossy(&first.stderr));
    assert_eq!(String::from_utf8_lossy(&first.stdout).trim(), "2");

    // The app's edit cannot reach the library, so its C++ is kept, even changed by hand.
    tamper(&lib_cpp);
    write_main(&dir, 2);
    let edited = dz(&dir, None);
    let stderr = String::from_utf8_lossy(&edited.stderr);
    assert!(edited.status.success(), "{stderr}");
    assert_eq!(String::from_utf8_lossy(&edited.stdout).trim(), "4");
    assert!(stderr.contains("DZ0406"), "the library's warning is printed again:\n{stderr}");
    let kept = std::fs::read_to_string(&lib_cpp).unwrap();
    assert!(kept.contains("generated by"), "the library's C++ was kept, not written again");

    // Verify emits the whole program too, and sees the file is not what it would write.
    write_main(&dir, 3);
    let verified = dz(&dir, Some("verify"));
    let stderr = String::from_utf8_lossy(&verified.stderr);
    assert!(!verified.status.success(), "verify must refuse a kept file that is wrong");
    assert!(stderr.contains("lib.cpp"), "it names the file:\n{stderr}");

    // Without reuse, every module is emitted, which puts the file right.
    let whole = dz(&dir, Some("0"));
    assert!(whole.status.success(), "{}", String::from_utf8_lossy(&whole.stderr));
    assert_eq!(String::from_utf8_lossy(&whole.stdout).trim(), "6");
    assert!(std::fs::read_to_string(&lib_cpp).unwrap().contains("Generated by"));
    let _ = std::fs::remove_dir_all(&dir);
}
