//! Libraries vendored as source, compiled by `dz` (spec §15.1).
//!
//! No build system is involved. A library's recipe in `dazzle.toml` names its sources,
//! include dirs and defines, and each source becomes one object in `build/obj/<library>/`.
//! An object is rebuilt only when something that went into it changed — the source, a
//! header it included, or the command that compiles it — judged by content rather than by
//! timestamp, as the generated C++ is (spec §16.6), so a checkout that touches every file
//! does not rebuild raylib.
//!
//! A library that names its own CMake build is the exception: CMake builds it, here, before
//! analysis reads its installed headers (spec §15.1, D-0090).

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};

use dz_diag::{codes, Diagnostic, Diagnostics};
use dz_project::{CmakeBuild, CppLib, Module, SourceLang, Workspace};

/// Write the one translation unit that carries a single-header library's implementation,
/// and return its path (spec §15.1).
///
/// Compiled as C for a `.h` header and as C++ otherwise, which is what the header itself
/// says it is. The recipe's own `defines` — `RGFW_IMPLEMENTATION`, `STB_IMAGE_IMPLEMENTATION`
/// — are in force here and nowhere else, which is exactly the rule that makes this work:
/// every other translation unit sees declarations only, so nothing is defined twice.
///
/// Written only when its contents would change, so it never makes an object stale.
fn implementation_unit(dir: &Path, lib: &CppLib, header: &Path) -> std::io::Result<PathBuf> {
    let cpp = header.extension().and_then(|e| e.to_str()) != Some("h");
    let path = dir.join(format!("dz_{}_impl.{}", lib.name, if cpp { "cpp" } else { "c" }));
    // Absolute: this file lives in `build/obj/<lib>/`, and a quoted include is searched from
    // there first, so a path relative to the manifest would not be found from it.
    let absolute = std::fs::canonicalize(header).unwrap_or_else(|_| header.to_path_buf());
    let include = absolute.to_string_lossy().trim_start_matches(r"\\?\").replace('\\', "/");
    let text = format!(
        "// Generated by the Dazzle compiler: the implementation of the single-header\n\
         // library `{}`, which `header` in its recipe asked for (spec §15.1). Do not edit.\n\
         #include \"{include}\"\n",
        lib.name
    );
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&path, &text)?;
    }
    Ok(path)
}

/// One source to compile.
struct Job<'w> {
    module: &'w Module,
    lib: &'w CppLib,
    source: PathBuf,
    object: PathBuf,
    args: Vec<String>,
}

/// Compile every vendored library the workspace uses, returning the objects to link.
///
/// `opt` is the build's optimisation flags, shared with the generated code so a debug
/// build is debuggable all the way into the library.
pub fn build_libraries(
    ws: &Workspace,
    cxx: &str,
    build_dir: &Path,
    opt: &[&str],
    cpp_standard: &str,
) -> Result<Vec<PathBuf>, Diagnostics> {
    let mut diags = Diagnostics::new();
    let mut objects = Vec::new();
    let mut jobs = Vec::new();

    for (module, lib) in ws.cpp_libs() {
        let dir = build_dir.join("obj").join(&lib.name);
        if let Err(e) = std::fs::create_dir_all(&dir) {
            diags.push(Diagnostic::error(
                codes::CPP_LIBRARY_FAILED,
                format!("cannot create {}: {e}", dir.display()),
            ));
            return Err(diags);
        }
        // A single-header library keeps its definitions behind an implementation macro, so
        // exactly one translation unit has to include it with that macro defined. That is
        // the only reason such a library needs a `.c` file at all, and writing one by hand
        // is a chore with a confusing failure — an unresolved symbol — when you forget. With
        // `header` in the recipe, `dz` writes it (spec §15.1).
        let mut sources = lib.sources.clone();
        if let Some(header) = &lib.header {
            match implementation_unit(&dir, lib, header) {
                Ok(path) => sources.push(path),
                Err(e) => {
                    diags.push(
                        Diagnostic::error(
                            codes::CPP_LIBRARY_FAILED,
                            format!("cannot write the implementation of `{}`: {e}", lib.name),
                        )
                        .at(module.manifest, lib.name_span, "this library"),
                    );
                    return Err(diags);
                }
            }
        }

        let mut stale = 0usize;
        for source in &sources {
            let mut args: Vec<String> = Vec::new();
            match dz_project::source_language(source) {
                Some(SourceLang::C) => args.extend(["-x".to_owned(), "c".to_owned()]),
                Some(SourceLang::Cpp) => {
                    args.extend(["-x".to_owned(), "c++".to_owned(), format!("-std={cpp_standard}")])
                }
                // The manifest refused anything else when it was read.
                None => continue,
            }
            args.extend(opt.iter().map(|s| (*s).to_owned()));
            // A library's warnings are not the project's to fix; invariant 7 is about the
            // code Dazzle generates.
            args.push("-w".to_owned());
            // The module's own `[cpp]` is for everything it builds, this library included:
            // a define that has to hold across the boundary — `JPH_PROFILE_ENABLED`, or a
            // single-header library's `RGFWDEF=` giving its declarations external linkage —
            // must reach the library's sources and the generated code alike (spec §15.1).
            // The library's own entries come after, so they win where the two disagree.
            args.extend(module.cpp.defines.iter().map(|d| format!("-D{d}")));
            args.extend(module.cpp.include_dirs.iter().map(|d| format!("-I{}", d.display())));
            args.extend(lib.defines.iter().map(|d| format!("-D{d}")));
            args.extend(lib.include_dirs.iter().map(|d| format!("-I{}", d.display())));
            // Last, so a recipe can override what `dz` chose — which is the point of the
            // key. `-x objective-c` after the `-x c` above is exactly that: the final `-x`
            // before the input is the one that applies (spec §15.1).
            args.extend(lib.flags.iter().cloned());

            // The object's name carries everything its bytes depend on besides its inputs'
            // contents, so changing a flag compiles a new object rather than reusing one.
            let mut key = Vec::new();
            for part in std::iter::once(cxx.to_owned())
                .chain(std::iter::once(source.to_string_lossy().into_owned()))
                .chain(args.iter().cloned())
            {
                key.extend_from_slice(part.as_bytes());
                key.push(0);
            }
            let stem =
                source.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
            let object = dir.join(format!("{stem}-{:016x}.o", fnv1a(&key)));
            objects.push(object.clone());

            if !up_to_date(&object) {
                stale += 1;
                jobs.push(Job { module, lib, source: source.clone(), object, args });
            }
        }
        if stale > 0 {
            eprintln!(
                "   compiling {} ({stale} file{})",
                lib.name,
                if stale == 1 { "" } else { "s" }
            );
        }
    }

    run_jobs(cxx, jobs, &mut diags);
    if diags.has_errors() {
        Err(diags)
    } else {
        Ok(objects)
    }
}

/// Run the compiles, as many at once as there are cores.
fn run_jobs(cxx: &str, jobs: Vec<Job<'_>>, diags: &mut Diagnostics) {
    let limit = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4);
    let mut pending = jobs.into_iter();
    let mut running: Vec<(Job<'_>, Child)> = Vec::new();
    loop {
        while running.len() < limit {
            let Some(job) = pending.next() else { break };
            let depfile = job.object.with_extension("d");
            let spawned = Command::new(cxx)
                .args(&job.args)
                .arg("-c")
                .arg(&job.source)
                .arg("-o")
                .arg(&job.object)
                .arg("-MD")
                .arg("-MF")
                .arg(&depfile)
                .stdout(Stdio::null())
                .stderr(Stdio::piped())
                .spawn();
            match spawned {
                Ok(child) => running.push((job, child)),
                Err(e) => diags.push(Diagnostic::error(
                    codes::CPP_LIBRARY_FAILED,
                    format!("could not run {cxx}: {e}"),
                )),
            }
        }
        if running.is_empty() {
            return;
        }
        let (job, child) = running.remove(0);
        match child.wait_with_output() {
            Ok(out) if out.status.success() => write_stamp(&job.source, &job.object),
            Ok(out) => {
                // A failed compile may leave a stale object behind; the stamp is what says
                // an object is good, and it is only written on success.
                let _ = std::fs::remove_file(job.object.with_extension("stamp"));
                let stderr = String::from_utf8_lossy(&out.stderr);
                diags.push(
                    Diagnostic::error(
                        codes::CPP_LIBRARY_FAILED,
                        format!(
                            "library `{}` failed to compile {}",
                            job.lib.name,
                            job.source.display()
                        ),
                    )
                    .at(job.module.manifest, job.lib.name_span, "the recipe for this library")
                    .with_note(stderr.trim().to_owned())
                    .with_help(
                        "the error is in the library's source or in its recipe: a missing entry \
                         in `defines` or `include_dirs` is the usual cause (spec §15.1)",
                    ),
                );
            }
            Err(e) => diags.push(Diagnostic::error(
                codes::CPP_LIBRARY_FAILED,
                format!("could not run {cxx}: {e}"),
            )),
        }
    }
}

/// An object is up to date when its stamp exists and every file it lists still has the
/// content it had when the object was compiled.
fn up_to_date(object: &Path) -> bool {
    if !object.exists() {
        return false;
    }
    let Ok(stamp) = std::fs::read_to_string(object.with_extension("stamp")) else { return false };
    let mut any = false;
    for line in stamp.lines() {
        let Some((hash, path)) = line.split_once(' ') else { return false };
        match std::fs::read(path) {
            Ok(bytes) if format!("{:016x}", fnv1a(&bytes)) == hash => any = true,
            _ => return false,
        }
    }
    any
}

/// Record what an object was compiled from: the source, and every header the compiler's
/// depfile names.
fn write_stamp(source: &Path, object: &Path) {
    let mut inputs = std::fs::read_to_string(object.with_extension("d"))
        .map(|d| depfile_inputs(&d))
        .unwrap_or_default();
    if !inputs.iter().any(|p| p == source) {
        inputs.insert(0, source.to_path_buf());
    }
    let mut stamp = String::new();
    for p in &inputs {
        let Ok(bytes) = std::fs::read(p) else { continue };
        stamp.push_str(&format!("{:016x} {}\n", fnv1a(&bytes), p.display()));
    }
    let _ = std::fs::write(object.with_extension("stamp"), stamp);
}

/// The prerequisites in a make-style depfile, as `-MD` writes it: `target: a b \` continued
/// over lines, with `\ ` an escaped space and `$$` a dollar. The target ends at the first
/// `: `, which a drive letter's colon never is.
fn depfile_inputs(text: &str) -> Vec<PathBuf> {
    let Some(colon) = text.find(": ") else { return Vec::new() };
    let mut out = Vec::new();
    let mut cur = String::new();
    let flush = |cur: &mut String, out: &mut Vec<PathBuf>| {
        if !cur.is_empty() {
            out.push(PathBuf::from(std::mem::take(cur)));
        }
    };
    let mut chars = text[colon + 2..].chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\\' => match chars.peek() {
                Some(' ') | Some('#') => {
                    cur.push(chars.next().unwrap_or(' '));
                }
                Some('\n') | Some('\r') => {
                    chars.next();
                    if chars.peek() == Some(&'\n') {
                        chars.next();
                    }
                    flush(&mut cur, &mut out);
                }
                _ => cur.push('\\'),
            },
            '$' if chars.peek() == Some(&'$') => {
                chars.next();
                cur.push('$');
            }
            ' ' | '\t' | '\n' | '\r' => flush(&mut cur, &mut out),
            _ => cur.push(c),
        }
    }
    flush(&mut cur, &mut out);
    out
}

/// Build and install every library whose recipe names its CMake build, with the compiler
/// this build uses (spec §15.1, D-0090). Runs before any header is read, since a CMake
/// library's headers are the ones its install holds; `dz_project` reads that install.
///
/// A library is configured, built and installed again only when its stamp says something
/// that went into it changed: a file under its source folder (by content, as for every
/// other input), an option, a compiler, the generator or the configuration.
pub fn build_cmake_libraries(ws: &Workspace, chosen: Option<&str>, diags: &mut Diagnostics) {
    let libs: Vec<(&Module, &CppLib, &CmakeBuild)> = ws
        .cpp_libs()
        .into_iter()
        .filter_map(|(m, l)| l.cmake.as_ref().map(|c| (m, l, c)))
        .collect();
    if libs.is_empty() {
        return;
    }
    let fail = |diags: &mut Diagnostics, m: &Module, l: &CppLib, msg: String, help: &str| {
        diags.push(
            Diagnostic::error(codes::CPP_CMAKE_FAILED, msg)
                .at(m.manifest, l.name_span, "this library is built with CMake")
                .with_help(help.to_owned()),
        );
    };

    let runs = |tool: &str| {
        Command::new(tool)
            .arg("--version")
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|s| s.success())
    };
    if !runs("cmake") {
        for (m, l, _) in &libs {
            fail(
                diags,
                m,
                l,
                format!("`{}` needs CMake, which is not installed", l.name),
                "install CMake (cmake.org, or the system's package manager); only a recipe \
                 with `cmake` needs it (spec §15.1)",
            );
        }
        return;
    }
    // Ninja when there is one. Without it CMake picks the platform's generator, which on
    // Windows is Visual Studio's, and that one ignores the compiler it is given (D-0090).
    let generator = runs("ninja").then_some("Ninja");
    if generator.is_none() && cfg!(windows) {
        for (m, l, _) in &libs {
            fail(
                diags,
                m,
                l,
                format!("`{}` needs Ninja to build with CMake on Windows", l.name),
                "install Ninja (ninja-build.org, or `winget install Ninja-build.Ninja`): \
                 CMake's default generator on Windows ignores the compiler `dz` uses \
                 (spec §15.1)",
            );
        }
        return;
    }
    let Some(cxx) = crate::build::find_compiler(Some(ws), chosen) else {
        for (m, l, _) in &libs {
            fail(
                diags,
                m,
                l,
                "no C++ compiler found".to_owned(),
                "install clang++ or g++, or name one with `--cxx` or `DZ_CXX`",
            );
        }
        return;
    };
    let cc = c_compiler_for(&cxx);

    for (module, lib, build) in libs {
        let setup = format!(
            "{cxx}\0{}\0{}\0{}",
            cc.as_deref().unwrap_or(""),
            generator.unwrap_or(""),
            build.config
        );
        let mut key = setup.clone().into_bytes();
        for (k, v) in &build.options {
            key.extend_from_slice(format!("\0{k}={v}").as_bytes());
        }
        key.extend_from_slice(&tree_hash(&build.source).to_le_bytes());
        let stamp = format!("{:016x}\n{:016x}\n", fnv1a(setup.as_bytes()), fnv1a(&key));
        let stamp_path = build.dir.join("dz-stamp");
        let old = std::fs::read_to_string(&stamp_path).unwrap_or_default();
        if old == stamp && build.install_dir().is_dir() {
            continue;
        }
        // A tree configured by another compiler or generator cannot be reconfigured in
        // place; CMake refuses. A changed option or source is an ordinary re-run.
        if old.lines().next() != stamp.lines().next() {
            let _ = std::fs::remove_dir_all(&build.dir);
        }
        let _ = std::fs::remove_file(&stamp_path);
        // CMake resolves a relative path against the build tree, not where `dz` runs.
        let absolute = |p: &Path| {
            if p.is_absolute() {
                p.to_path_buf()
            } else {
                std::env::current_dir().map_or_else(|_| p.to_path_buf(), |d| d.join(p))
            }
        };
        let (build_dir, install_dir) =
            (absolute(&build.build_dir()), absolute(&build.install_dir()));
        eprintln!("   building {} with CMake ({})", lib.name, build.config);

        let mut configure = Command::new("cmake");
        configure.arg("-S").arg(absolute(&build.source)).arg("-B").arg(&build_dir);
        if let Some(g) = generator {
            configure.args(["-G", g]);
        }
        configure.arg(format!("-DCMAKE_BUILD_TYPE={}", build.config));
        configure.arg(format!("-DCMAKE_INSTALL_PREFIX={}", slashes(&install_dir)));
        // `lib`, not `lib64`, wherever the platform would choose, so the install has one
        // shape to read.
        configure.arg("-DCMAKE_INSTALL_LIBDIR=lib");
        configure.arg(format!("-DCMAKE_CXX_COMPILER={cxx}"));
        if let Some(cc) = &cc {
            configure.arg(format!("-DCMAKE_C_COMPILER={cc}"));
        }
        // Static, so the program is one executable, as with a source recipe (D-0090).
        configure.arg("-DBUILD_SHARED_LIBS=OFF");
        // CMake 4 refuses a project that asks for a CMake older than 3.5, which many
        // libraries still do without needing anything that old.
        configure.arg("-DCMAKE_POLICY_VERSION_MINIMUM=3.5");
        // clang targeting MSVC links the static C runtime by default; CMake would build
        // against the DLL one, and the two do not mix in one program.
        if cfg!(windows) {
            configure.arg("-DCMAKE_MSVC_RUNTIME_LIBRARY=MultiThreaded");
        }
        for (k, v) in &build.options {
            configure.arg(format!("-D{k}={v}"));
        }
        let mut build_cmd = Command::new("cmake");
        build_cmd.arg("--build").arg(&build_dir).args(["--config", build.config, "--parallel"]);
        let mut install = Command::new("cmake");
        install.arg("--install").arg(&build_dir).args(["--config", build.config]);

        let _ = std::fs::remove_dir_all(&install_dir);
        let steps = [("configure", configure), ("build", build_cmd), ("install", install)];
        let mut ok = true;
        for (step, mut cmd) in steps {
            match cmd.output() {
                Ok(out) if out.status.success() => {}
                Ok(out) => {
                    diags.push(
                        Diagnostic::error(
                            codes::CPP_CMAKE_FAILED,
                            format!("CMake could not {step} `{}`", lib.name),
                        )
                        .at(module.manifest, lib.name_span, "this library is built with CMake")
                        .with_note(format!("{}{}", tail(&out.stdout), tail(&out.stderr)))
                        .with_help(format!(
                            "the whole log is in {}; a failed configure is usually an \
                             `options` value the library does not accept (spec §15.1)",
                            build_dir.display()
                        )),
                    );
                    ok = false;
                    break;
                }
                Err(e) => {
                    fail(
                        diags,
                        module,
                        lib,
                        format!("could not run cmake: {e}"),
                        "check that CMake is installed and on the path (spec §15.1)",
                    );
                    ok = false;
                    break;
                }
            }
        }
        if ok {
            let _ = std::fs::write(&stamp_path, stamp);
        }
    }
}

/// The C compiler of the same family as `cxx`, which CMake needs for a library's C sources:
/// `clang` for `clang++`, `gcc` for `g++`, `cc` for `c++`, keeping any target prefix and
/// version suffix (`x86_64-w64-mingw32-g++` → `x86_64-w64-mingw32-gcc`). `None` for a name
/// that says neither, which leaves CMake to find one.
fn c_compiler_for(cxx: &str) -> Option<String> {
    let path = Path::new(cxx);
    let file = path.file_name()?.to_str()?;
    let (stem, ext) = match file.strip_suffix(".exe") {
        Some(s) => (s, ".exe"),
        None => (file, ""),
    };
    let c =
        [("clang++", "clang"), ("g++", "gcc"), ("c++", "cc")].iter().find_map(|(from, to)| {
            stem.rfind(from).map(|i| format!("{}{to}{}{ext}", &stem[..i], &stem[i + from.len()..]))
        })?;
    Some(path.with_file_name(c).to_string_lossy().into_owned())
}

/// Every file under `dir`, by path and content, in a fixed order. `.git` is passed over: a
/// submodule's checkout metadata says nothing about what it builds.
fn tree_hash(dir: &Path) -> u64 {
    let mut files = Vec::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(d) = pending.pop() {
        for e in std::fs::read_dir(&d).into_iter().flatten().flatten() {
            let p = e.path();
            match e.file_type() {
                Ok(t) if t.is_dir() && e.file_name() != ".git" => pending.push(p),
                Ok(t) if t.is_file() => files.push(p),
                _ => {}
            }
        }
    }
    files.sort();
    let mut all = Vec::new();
    for f in files {
        let rel = f.strip_prefix(dir).unwrap_or(&f).to_string_lossy().replace('\\', "/");
        all.extend_from_slice(rel.as_bytes());
        all.push(0);
        if let Ok(bytes) = std::fs::read(&f) {
            all.extend_from_slice(&fnv1a(&bytes).to_le_bytes());
        }
    }
    fnv1a(&all)
}

/// A path as CMake writes them, which a backslash in a `-D` value would escape.
fn slashes(p: &Path) -> String {
    p.to_string_lossy().trim_start_matches(r"\\?\").replace('\\', "/")
}

/// The last lines of a step's output, where its error is.
fn tail(bytes: &[u8]) -> String {
    let text = String::from_utf8_lossy(bytes);
    let lines: Vec<&str> = text.lines().collect();
    let mut out = lines[lines.len().saturating_sub(25)..].join("\n");
    if !out.is_empty() {
        out.push('\n');
    }
    out
}

/// FNV-1a, 64 bits: stable across Rust versions and platforms, which `DefaultHasher` does
/// not promise, and a cache key needs.
fn fnv1a(bytes: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in bytes {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    h
}

#[cfg(test)]
mod tests {
    use super::{c_compiler_for, depfile_inputs};
    use std::path::PathBuf;

    #[test]
    fn cmake_gets_the_c_compiler_of_the_same_family() {
        assert_eq!(c_compiler_for("clang++").as_deref(), Some("clang"));
        assert_eq!(c_compiler_for("g++-14").as_deref(), Some("gcc-14"));
        assert_eq!(
            c_compiler_for("x86_64-w64-mingw32-g++").as_deref(),
            Some("x86_64-w64-mingw32-gcc")
        );
        assert_eq!(c_compiler_for("/usr/bin/c++").as_deref(), Some("/usr/bin/cc"));
        assert_eq!(c_compiler_for("clang++.exe").as_deref(), Some("clang.exe"));
        assert_eq!(c_compiler_for("icpx"), None);
    }

    #[test]
    fn a_depfile_lists_its_inputs_across_continuations() {
        let d = "D:/x/build/obj/mini/mini-1.o: D:/x/vendor/mini/mini.c \\\n  D:/x/vendor/mini/include/mini.h \\\r\n  C:/Program\\ Files/inc/stdio.h\n";
        assert_eq!(
            depfile_inputs(d),
            vec![
                PathBuf::from("D:/x/vendor/mini/mini.c"),
                PathBuf::from("D:/x/vendor/mini/include/mini.h"),
                PathBuf::from("C:/Program Files/inc/stdio.h"),
            ]
        );
    }
}
