//! C++17 code generation (spec §16).
//!
//! One header and one translation unit per module (§16.1), `dz::`-scoped names (§16.2),
//! and a `#line` directive before every statement so debuggers, profilers and any C++
//! error that slips through all point at `.dz` source (§16.3).
//!
//! **Scope at M4.** Codegen covers what a non-generic program needs to run: functions,
//! structs with fields, methods and constructors, enums, primitives, control flow,
//! pointers and references, arrays and slices, `defer`, and the print builtins. Anything
//! else reports [`codes::CODEGEN_UNSUPPORTED`] with a span rather than emitting something
//! subtly wrong. The deferral register in `docs/PROGRESS.md` lists what is outstanding and
//! which milestone owns it; the largest items are `?T`/`!T` and tagged unions, both of
//! which want the statement-level desugaring that arrives with M5.

use std::collections::{HashMap, HashSet};
use std::fmt::Write;

use dz_ast::*;
use dz_diag::{codes, Diagnostic, Diagnostics};
use dz_project::{ModuleId, Workspace};
use dz_resolve::{ParsedFile, Resolution, SymbolId, SymbolKind};
use dz_span::{FileId, SourceMap, Span};

mod runtime;

pub use runtime::{PRELUDE_H, RUNTIME_CPP, RUNTIME_H};

#[derive(Debug, Clone)]
pub struct GeneratedFile {
    /// Path relative to the build directory, e.g. `cpp/engine.h`.
    pub name: String,
    pub contents: String,
}

pub struct Emitted {
    pub files: Vec<GeneratedFile>,
    pub diagnostics: Diagnostics,
    /// The translation unit holding the real `int main()`, if the root module has one.
    pub entry: Option<String>,
}

pub fn emit(
    ws: &Workspace,
    res: &Resolution,
    map: &SourceMap,
    files: &HashMap<ModuleId, Vec<ParsedFile>>,
) -> Emitted {
    // The root module's setting governs the whole build, since one C++ invocation
    // compiles every translation unit.
    let standard = cpp_standard_version(&ws.module(ws.root).build.cpp_standard);

    let mut out = Emitted {
        files: vec![
            GeneratedFile { name: "dz_runtime.h".into(), contents: RUNTIME_H.into() },
            GeneratedFile { name: "dz_runtime.cpp".into(), contents: RUNTIME_CPP.into() },
            GeneratedFile { name: "dz_prelude.h".into(), contents: PRELUDE_H.into() },
        ],
        diagnostics: Diagnostics::new(),
        entry: None,
    };

    for module in ws.modules() {
        let Some(module_files) = files.get(&module.id) else { continue };
        let mut e = Emitter {
            ws,
            res,
            map,
            module: module.id,
            file: FileId(0),
            diags: Diagnostics::new(),
            header: String::new(),
            body: String::new(),
            indent: 0,
            temp: 0,
            current_fn: String::new(),
            last_line: 0,
            enum_bindings: Vec::new(),
            standard,
        };
        e.module(module_files);

        let stem = file_stem(&module.name);
        let ns_open = namespace_open(&module.name);
        let ns_close = namespace_close(&module.name);

        let mut includes = String::from("#include \"dz_runtime.h\"\n#include \"dz_prelude.h\"\n");
        for dep in &module.deps {
            let _ = writeln!(includes, "#include \"{}.h\"", file_stem(&ws.module(dep.module).name));
        }

        let guard = format!("DZ_{}_H", stem.to_uppercase());
        let header = format!(
            "// Generated by the Dazzle compiler from module `{}`. Do not edit.\n\
             #ifndef {guard}\n#define {guard}\n\n{includes}\n{ns_open}\n{}\n{ns_close}\n\
             #endif  // {guard}\n",
            module.name, e.header
        );
        let body = format!(
            "// Generated by the Dazzle compiler from module `{}`. Do not edit.\n\
             #include \"{stem}.h\"\n\n{ns_open}\n{}\n{ns_close}\n",
            module.name, e.body
        );

        out.files.push(GeneratedFile { name: format!("{stem}.h"), contents: header });
        out.files.push(GeneratedFile { name: format!("{stem}.cpp"), contents: body });
        out.diagnostics.extend(e.diags);

        // The root module's `main` becomes the program's real entry point.
        if module.id == ws.root {
            if res.lookup(module.id, "main").is_some() {
                let entry = format!(
                    "// Generated by the Dazzle compiler. Do not edit.\n\
                     #include \"{stem}.h\"\n\n\
                     int main() {{\n    {}::main();\n    return 0;\n}}\n",
                    qualified_namespace(&module.name)
                );
                out.files
                    .push(GeneratedFile { name: "dz_main.cpp".into(), contents: entry });
                out.entry = Some("dz_main.cpp".into());
            } else {
                out.diagnostics.push(
                    Diagnostic::error(
                        codes::NO_ENTRY_POINT,
                        format!("module `{}` has no `main`", module.name),
                    )
                    .with_help(
                        "an executable needs `fn main()`; set `output = \"static-lib\"` in \
                         dazzle.toml if this is a library",
                    ),
                );
            }
        }
    }

    out.diagnostics.sort_by_position();
    out
}

// ---------------------------------------------------------------------------

struct Emitter<'a> {
    ws: &'a Workspace,
    res: &'a Resolution,
    map: &'a SourceMap,
    module: ModuleId,
    file: FileId,
    diags: Diagnostics,
    header: String,
    body: String,
    indent: usize,
    temp: u32,
    current_fn: String,
    last_line: u32,
    /// The C++ standard being targeted, as a year: 17, 20, 23.
    standard: u32,
    /// Bindings whose declared type is an enum, mapped to its qualified C++ name.
    ///
    /// C++ `enum class` case labels must be qualified, so `switch` needs the subject's
    /// type. This is the one place codegen needs a type it cannot read off the syntax;
    /// when the typed HIR lands (M5) it replaces this table.
    enum_bindings: Vec<HashMap<String, String>>,
}

impl<'a> Emitter<'a> {
    fn unsupported(&mut self, span: Span, what: &str, owner: &str) {
        self.diags.push(
            Diagnostic::error(
                codes::CODEGEN_UNSUPPORTED,
                format!("{what} is not generated yet"),
            )
            .at(self.file, span, "no C++ is emitted for this")
            .with_help(format!(
                "{owner} — see the deferral register in docs/PROGRESS.md"
            )),
        );
    }

    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.body.push_str("    ");
        }
        self.body.push_str(text);
        self.body.push('\n');
    }

    /// Emit a `#line` directive so this statement maps back to `.dz` (spec §16.3).
    fn line_directive(&mut self, span: Span) {
        let loc = self.map.get(self.file).location(span.start as usize);
        if loc.line == self.last_line {
            return;
        }
        self.last_line = loc.line;
        let path = self.map.get(self.file).name();
        self.body.push_str(&format!("#line {} \"{}\"\n", loc.line, path.replace('\\', "/")));
    }

    /// A `dz::SourceLocation` literal for the runtime helpers.
    fn source_location(&self, span: Span) -> String {
        let f = self.map.get(self.file);
        let loc = f.location(span.start as usize);
        format!(
            "dz::SourceLocation{{\"{}\", \"{}\", {}, {}}}",
            f.name().replace('\\', "/"),
            self.current_fn,
            loc.line,
            loc.column
        )
    }

    fn fresh(&mut self, prefix: &str) -> String {
        self.temp += 1;
        format!("_dz_{prefix}{}", self.temp)
    }

    // --- module ------------------------------------------------------------

    fn module(&mut self, files: &[ParsedFile]) {
        // Types must be declared before anything uses them by value, and a module's files
        // are one namespace with no ordering, so sort by dependency first.
        let mut types: Vec<(FileId, &Item)> = Vec::new();
        let mut functions: Vec<(FileId, &Item)> = Vec::new();
        for pf in files {
            for item in &pf.ast.items {
                match &item.kind {
                    ItemKind::Struct(_) | ItemKind::Enum(_) => types.push((pf.file, item)),
                    ItemKind::Fn(_) | ItemKind::Const(_) => functions.push((pf.file, item)),
                    ItemKind::Union(u) => {
                        self.file = pf.file;
                        self.unsupported(u.name.span, "a tagged union", "owed by M5");
                    }
                    ItemKind::Trait(_) | ItemKind::Macro(_)
                    | ItemKind::MacroInvocation { .. } | ItemKind::Error => {}
                }
            }
        }

        let types = sort_by_dependency(types);

        for (file, item) in &types {
            self.file = *file;
            match &item.kind {
                ItemKind::Struct(s) => self.struct_decl(s, item),
                ItemKind::Enum(e) => self.enum_decl(e),
                _ => {}
            }
        }
        for (file, item) in &functions {
            self.file = *file;
            match &item.kind {
                ItemKind::Fn(f) => self.free_fn(f),
                ItemKind::Const(c) => self.const_decl(c),
                _ => {}
            }
        }
        // Method bodies come last so they can call anything in the module.
        for (file, item) in &types {
            self.file = *file;
            if let ItemKind::Struct(s) = &item.kind {
                self.struct_bodies(s);
            }
        }
    }

    fn const_decl(&mut self, c: &ConstDecl) {
        let ty = match &c.ty {
            Some(t) => self.ty(t),
            None => "auto".to_owned(),
        };
        let value = self.expr(&c.value);
        let _ = writeln!(
            self.header,
            "inline constexpr {ty} {} = {value};",
            c.name.name
        );
    }

    fn enum_decl(&mut self, e: &EnumDecl) {
        let backing = match &e.backing {
            Some(t) => self.ty(t),
            None => "int32_t".to_owned(),
        };
        let _ = writeln!(self.header, "enum class {} : {backing} {{", e.name.name);
        for v in &e.variants {
            match &v.value {
                Some(val) => {
                    let text = self.expr(val);
                    let _ = writeln!(self.header, "    {} = {text},", v.name.name);
                }
                None => {
                    let _ = writeln!(self.header, "    {},", v.name.name);
                }
            }
        }
        self.header.push_str("};\n\n");
    }

    fn struct_decl(&mut self, s: &StructDecl, item: &Item) {
        if !s.generics.is_empty() {
            self.unsupported(s.name.span, "a generic struct", "owed by M6");
            return;
        }
        let _ = item;
        let _ = writeln!(self.header, "struct {} {{", s.name.name);

        for m in &s.members {
            if let MemberKind::Field(f) = &m.kind {
                let ty = self.ty(&f.ty);
                match &f.default {
                    Some(d) => {
                        let v = self.expr(d);
                        let _ = writeln!(self.header, "    {ty} {} = {v};", f.name.name);
                    }
                    // Value initialisation, so every field is zeroed (spec §6.2).
                    None => {
                        let _ = writeln!(self.header, "    {ty} {}{{}};", f.name.name);
                    }
                }
            }
        }

        let mut any_ctor = false;
        for m in &s.members {
            match &m.kind {
                MemberKind::Ctor(f) => {
                    any_ctor = true;
                    let params = self.params(f, true);
                    let _ = writeln!(self.header, "    {}({params});", s.name.name);
                }
                MemberKind::Fn(f) => {
                    if !f.generics.is_empty() {
                        self.unsupported(f.name.span, "a generic method", "owed by M6");
                        continue;
                    }
                    let params = self.params(f, true);
                    let ret = self.ret_ty(f);
                    let cst = if f.is_mut { "" } else { " const" };
                    let _ = writeln!(self.header, "    {ret} {}({params}){cst};", f.name.name);
                }
                MemberKind::Copy(_) | MemberKind::Drop(_) => {
                    // `copy` and `drop` become C++ special members with M5's ownership
                    // rules; emitting them before those rules exist would be guesswork.
                }
                _ => {}
            }
        }
        // A struct with a user constructor loses its implicit default one, and spec §6.2
        // requires `let v: T` to work.
        if any_ctor {
            let _ = writeln!(self.header, "    {}() = default;", s.name.name);
        }
        self.header.push_str("};\n\n");
    }

    fn struct_bodies(&mut self, s: &StructDecl) {
        if !s.generics.is_empty() {
            return;
        }
        for m in &s.members {
            match &m.kind {
                MemberKind::Ctor(f) => {
                    let params = self.params(f, false);
                    self.current_fn = format!("{}::{}", s.name.name, s.name.name);
                    self.line(&format!("{}::{}({params}) {{", s.name.name, s.name.name));
                    self.emit_body(f);
                }
                MemberKind::Fn(f) if f.generics.is_empty() => {
                    let params = self.params(f, false);
                    let ret = self.ret_ty(f);
                    let cst = if f.is_mut { "" } else { " const" };
                    self.current_fn = format!("{}::{}", s.name.name, f.name.name);
                    self.line(&format!(
                        "{ret} {}::{}({params}){cst} {{",
                        s.name.name, f.name.name
                    ));
                    self.emit_body(f);
                }
                _ => {}
            }
        }
    }

    fn free_fn(&mut self, f: &FnDecl) {
        if !f.generics.is_empty() {
            self.unsupported(f.name.span, "a generic function", "owed by M6");
            return;
        }
        let params_decl = self.params(f, true);
        let ret = self.ret_ty(f);
        let _ = writeln!(self.header, "{ret} {}({params_decl});", f.name.name);

        let params = self.params(f, false);
        self.current_fn = f.name.name.clone();
        self.line(&format!("{ret} {}({params}) {{", f.name.name));
        self.emit_body(f);
    }

    fn emit_body(&mut self, f: &FnDecl) {
        self.indent += 1;
        self.last_line = 0;
        self.enum_bindings.push(HashMap::new());
        for p in &f.params {
            if let Some(e) = self.enum_type_name(&p.ty) {
                self.note_enum(&p.name.name, e);
            }
        }
        if let Some(body) = &f.body {
            for s in &body.stmts {
                self.stmt(s);
            }
        }
        self.indent -= 1;
        self.line("}");
        self.body.push('\n');
    }

    /// `with_defaults` controls whether default arguments are printed, which C++ allows
    /// only on the declaration.
    fn params(&mut self, f: &FnDecl, with_defaults: bool) -> String {
        let mut parts: Vec<String> = Vec::new();
        for p in &f.params {
            let ty = self.ty(&p.ty);
            let mut s = format!("{ty} {}", p.name.name);
            if with_defaults {
                if let Some(d) = &p.default {
                    let v = self.expr(d);
                    s.push_str(&format!(" = {v}"));
                }
            }
            parts.push(s);
        }
        parts.join(", ")
    }

    fn ret_ty(&mut self, f: &FnDecl) -> String {
        match &f.ret {
            Some(t) => self.ty(t),
            None => "void".to_owned(),
        }
    }

    // --- types -------------------------------------------------------------

    fn ty(&mut self, t: &Type) -> String {
        match &t.kind {
            TypeKind::Path(p) => self.type_path(p, t.span),
            TypeKind::Ptr(i) | TypeKind::OwnPtr(i) => format!("{}*", self.ty(i)),
            TypeKind::Ref { mutable: true, inner } => format!("{}&", self.ty(inner)),
            TypeKind::Ref { mutable: false, inner } => format!("const {}&", self.ty(inner)),
            TypeKind::Optional(i) => format!("dz::Opt<{}>", self.ty(i)),
            TypeKind::Fallible(i) => format!("dz::Res<{}>", self.ty(i)),
            TypeKind::Array { size: Some(n), elem } => {
                let len = self.expr(n);
                format!("dz::Array<{}, {len}>", self.ty(elem))
            }
            TypeKind::Array { size: None, elem } => format!("dz::Slice<{}>", self.ty(elem)),
            TypeKind::Tuple(elems) => {
                let parts: Vec<String> = elems.iter().map(|e| self.ty(e)).collect();
                format!("dz::Tuple<{}>", parts.join(", "))
            }
            TypeKind::Fn { params, ret } => {
                let ps: Vec<String> = params.iter().map(|p| self.ty(p)).collect();
                let r = ret.as_ref().map(|r| self.ty(r)).unwrap_or("void".to_owned());
                format!("{r}(*)({})", ps.join(", "))
            }
            TypeKind::SelfType => "auto".to_owned(),
            TypeKind::Error => "void".to_owned(),
        }
    }

    fn type_path(&mut self, p: &Path, span: Span) -> String {
        let Some(first) = p.segments.first() else { return "void".into() };
        let name = first.name.name.as_str();
        if let Some(prim) = primitive(name) {
            return prim.to_owned();
        }
        if p.segments.len() > 1 {
            if let Some(target) = self.res.module_alias(self.file, name) {
                let seg = &p.segments[1].name.name;
                return format!("{}::{seg}", qualified_namespace(&self.ws.module(target).name));
            }
        }
        if let Some(sym) = self.res.lookup_in_file(self.module, self.file, name) {
            let s = self.res.symbol(sym);
            if s.module == self.module {
                return s.name.clone();
            }
            return format!("{}::{}", qualified_namespace(&self.ws.module(s.module).name), s.name);
        }
        self.unsupported(span, "this type", "owed by M6");
        "void".to_owned()
    }

    // --- statements --------------------------------------------------------

    fn stmt(&mut self, s: &Stmt) {
        self.line_directive(s.span);
        match &s.kind {
            StmtKind::Let(l) => {
                let PatKind::Ident(name) = &l.pat.kind else {
                    self.unsupported(l.pat.span, "tuple destructuring", "owed by M5");
                    return;
                };
                match (&l.ty, &l.init) {
                    (Some(t), Some(init)) => {
                        if let Some(e) = self.enum_type_name(t) {
                            self.note_enum(&name.name, e);
                        }
                        let ty = self.ty(t);
                        let v = self.expr(init);
                        self.line(&format!("{ty} {} = {v};", name.name));
                    }
                    // Declared with no value: default-initialise (spec §6.2).
                    (Some(t), None) => {
                        if let Some(e) = self.enum_type_name(t) {
                            self.note_enum(&name.name, e);
                        }
                        let ty = self.ty(t);
                        self.line(&format!("{ty} {}{{}};", name.name));
                    }
                    (None, Some(init)) => {
                        // A reference binding must stay a reference; `auto` would copy.
                        let (keyword, v) = match &init.kind {
                            ExprKind::Ref { mutable: true, expr } => {
                                ("auto&", self.expr(expr))
                            }
                            ExprKind::Ref { mutable: false, expr } => {
                                ("const auto&", self.expr(expr))
                            }
                            _ => ("auto", self.expr(init)),
                        };
                        self.line(&format!("{keyword} {} = {v};", name.name));
                    }
                    (None, None) => {}
                }
            }
            StmtKind::Assign { target, op, value } => {
                let t = self.expr(target);
                let v = self.expr(value);
                self.line(&format!("{t} {} {v};", op.as_str()));
            }
            StmtKind::Expr(e) => match &e.kind {
                ExprKind::If(_) | ExprKind::Block(_) | ExprKind::Switch(_) => {
                    self.control_flow(e)
                }
                _ => {
                    let text = self.expr(e);
                    self.line(&format!("{text};"));
                }
            },
            StmtKind::While(w) => {
                let rendered = self.expr(&w.cond);
                let cond = unwrap_parens(&rendered);
                self.line(&format!("while ({cond}) {{"));
                self.indent += 1;
                for s in &w.body.stmts {
                    self.stmt(s);
                }
                self.indent -= 1;
                self.line("}");
            }
            StmtKind::For(f) => self.for_loop(f),
            StmtKind::Defer(inner) => {
                // Captured by reference so the deferred code sees the final values.
                let name = self.fresh("defer");
                self.line(&format!("auto {name} = dz::make_defer([&] {{"));
                self.indent += 1;
                self.stmt(inner);
                self.indent -= 1;
                self.line("});");
            }
            // Nested declarations are emitted at module scope by the outer walk.
            StmtKind::Item(_) | StmtKind::Error => {}
        }
    }

    fn for_loop(&mut self, f: &ForStmt) {
        if f.bindings.len() != 1 {
            self.unsupported(f.span, "a `for` loop with several bindings", "owed by M6");
            return;
        }
        let PatKind::Ident(name) = &f.bindings[0].kind else {
            self.unsupported(f.bindings[0].span, "this loop pattern", "owed by M5");
            return;
        };

        if let ExprKind::Range { start, end, inclusive } = &f.iter.kind {
            let lo = start.as_ref().map(|s| self.expr(s)).unwrap_or("0".to_owned());
            let hi = end.as_ref().map(|s| self.expr(s)).unwrap_or("0".to_owned());
            let cmp = if *inclusive { "<=" } else { "<" };
            self.line(&format!(
                "for (auto {n} = {lo}; {n} {cmp} {hi}; ++{n}) {{",
                n = name.name
            ));
        } else {
            let iter = self.expr(&f.iter);
            self.line(&format!("for (auto& {} : dz::obj({iter})) {{", name.name));
        }
        self.indent += 1;
        for s in &f.body.stmts {
            self.stmt(s);
        }
        self.indent -= 1;
        self.line("}");
    }

    /// `if` / `switch` / a bare block in statement position.
    fn control_flow(&mut self, e: &Expr) {
        match &e.kind {
            ExprKind::If(i) => {
                let rendered = self.expr(&i.cond);
                let cond = unwrap_parens(&rendered);
                self.line(&format!("if ({cond}) {{"));
                self.indent += 1;
                for s in &i.then.stmts {
                    self.stmt(s);
                }
                self.indent -= 1;
                match &i.else_branch {
                    Some(other) => match &other.kind {
                        ExprKind::If(_) => {
                            self.line("} else");
                            self.control_flow(other);
                        }
                        ExprKind::Block(b) => {
                            self.line("} else {");
                            self.indent += 1;
                            for s in &b.stmts {
                                self.stmt(s);
                            }
                            self.indent -= 1;
                            self.line("}");
                        }
                        _ => self.line("}"),
                    },
                    None => self.line("}"),
                }
            }
            ExprKind::Block(b) => {
                self.line("{");
                self.indent += 1;
                for s in &b.stmts {
                    self.stmt(s);
                }
                self.indent -= 1;
                self.line("}");
            }
            ExprKind::Switch(s) => self.switch(s),
            _ => {}
        }
    }

    fn switch(&mut self, s: &SwitchExpr) {
        // Only enums for now: a tagged union needs the payload layout and drop rules that
        // M5 settles.
        let subject_ty = self
            .switch_enum(&s.subject)
            .or_else(|| self.enum_by_variant(s.arms.first()?.patterns.first()?));
        let Some(enum_name) = subject_ty else {
            self.unsupported(s.span, "`switch` on a tagged union", "owed by M5");
            return;
        };
        let subject = self.expr(&s.subject);
        self.line(&format!("switch ({subject}) {{"));
        for arm in &s.arms {
            for p in &arm.patterns {
                if p.binding.is_some() {
                    self.unsupported(p.span, "a `case` payload binding", "owed by M5");
                }
                self.line(&format!("case {enum_name}::{}:", p.name.name));
            }
            self.line("{");
            self.indent += 1;
            for st in &arm.body.stmts {
                self.stmt(st);
            }
            self.line("break;");
            self.indent -= 1;
            self.line("}");
        }
        if let Some(d) = &s.default {
            self.line("default: {");
            self.indent += 1;
            for st in &d.stmts {
                self.stmt(st);
            }
            self.line("break;");
            self.indent -= 1;
            self.line("}");
        }
        self.line("}");
    }

    /// Find the enum that declares `pat`'s variant, for a subject whose type codegen
    /// cannot read off the syntax.
    fn enum_by_variant(&mut self, pat: &VariantPat) -> Option<String> {
        let scope = self.res.scopes.get(&self.module)?;
        let mut found: Option<SymbolId> = None;
        for id in scope.items.values() {
            let sym = self.res.symbol(*id);
            if sym.kind == SymbolKind::Enum
                && sym.members.iter().any(|m| m.name == pat.name.name)
            {
                if found.is_some() {
                    return None; // two enums share the name; refuse to guess
                }
                found = Some(*id);
            }
        }
        found.map(|id| self.qualify(id))
    }

    fn note_enum(&mut self, binding: &str, enum_name: String) {
        if let Some(scope) = self.enum_bindings.last_mut() {
            scope.insert(binding.to_owned(), enum_name);
        }
    }

    /// The qualified C++ name of `t`, if `t` names an enum.
    fn enum_type_name(&mut self, t: &Type) -> Option<String> {
        let TypeKind::Path(p) = &t.kind else { return None };
        let first = p.segments.first()?;
        let sym = if p.segments.len() >= 2 {
            let target = self.res.module_alias(self.file, &first.name.name)?;
            self.res.lookup(target, &p.segments[1].name.name)?
        } else {
            self.res.lookup_in_file(self.module, self.file, &first.name.name)?
        };
        if self.res.symbol(sym).kind != SymbolKind::Enum {
            return None;
        }
        Some(self.qualify(sym))
    }

    /// The C++ name of the enum a `switch` subject has, if it is one.
    fn switch_enum(&mut self, subject: &Expr) -> Option<String> {
        if let ExprKind::Path(p) = &subject.kind {
            if p.segments.len() == 1 {
                let name = &p.segments[0].name.name;
                if let Some(found) =
                    self.enum_bindings.iter().rev().find_map(|s| s.get(name)).cloned()
                {
                    return Some(found);
                }
            }
        }
        // Fall back to the arms: a `case` names a variant, and the type checker has
        // already confirmed every arm belongs to the same type.
        None
    }

    // --- expressions -------------------------------------------------------

    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Int(text) => clean_number(text),
            ExprKind::Float(text) => {
                let n = clean_number(text);
                if text.ends_with('f') || text.ends_with("f32") {
                    format!("{n}f")
                } else {
                    n
                }
            }
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Null => "nullptr".to_owned(),
            ExprKind::Str(text) => {
                let body = &text[1..text.len() - 1];
                format!("dz::str({}, {})", quote_cpp(body), unescaped_len(body))
            }
            ExprKind::RawStr(text) => {
                let body = &text[1..text.len() - 1];
                format!("dz::str(R\"dz({body})dz\", {})", body.len())
            }
            ExprKind::Char(text) => {
                let body = &text[1..text.len() - 1];
                format!("U{}", quote_cpp(body))
            }
            ExprKind::Path(p) => self.value_path(p, e.span),
            ExprKind::Field { base, name } => {
                let b = self.expr(base);
                format!("dz::obj({b}).{}", name.name)
            }
            ExprKind::Index { base, index } => {
                let b = self.expr(base);
                let i = self.expr(index);
                let loc = self.source_location(e.span);
                format!("dz::index(dz::obj({b}), static_cast<size_t>({i}), {loc})")
            }
            ExprKind::Unary { op, operand } => {
                let o = self.expr(operand);
                format!("{}({o})", op.as_str())
            }
            ExprKind::Binary { op, lhs, rhs } => {
                let a = self.expr(lhs);
                let b = self.expr(rhs);
                let sym = match op {
                    // `^^` is Dazzle's xor; C++ spells it `^` (spec §2.6).
                    BinaryOp::BitXor => "^",
                    other => other.as_str(),
                };
                format!("({a} {sym} {b})")
            }
            ExprKind::Cast { expr, ty } => {
                let v = self.expr(expr);
                let t = self.ty(ty);
                format!("dz::cast<{t}>({v})")
            }
            // `&x` yields a proxy convertible to both `T&` and `T*`; a `let` binding
            // takes the plain form instead, since `auto&` cannot bind to the proxy.
            ExprKind::Ref { expr, .. } => {
                let v = self.expr(expr);
                format!("dz::addr({v})")
            }
            ExprKind::Deref(inner) => {
                let v = self.expr(inner);
                format!("(*({v}))")
            }
            // Real moves arrive with M5's ownership rules; until then this is a copy.
            ExprKind::Move(inner) => self.expr(inner),
            ExprKind::Call { callee, args } => self.call(callee, args, e.span),
            ExprKind::StructLit { path, fields } => self.struct_literal(path, fields, e.span),
            ExprKind::Return(v) => match v {
                Some(v) => {
                    let text = self.expr(v);
                    format!("return {text}")
                }
                None => "return".to_owned(),
            },
            ExprKind::Break { .. } => "break".to_owned(),
            ExprKind::Continue { .. } => "continue".to_owned(),
            ExprKind::None => "{}".to_owned(),
            ExprKind::Intrinsic { name, .. } => match name.name.as_str() {
                "line" => {
                    let f = self.map.get(self.file);
                    format!("{}u", f.location(e.span.start as usize).line)
                }
                "column" => {
                    let f = self.map.get(self.file);
                    format!("{}u", f.location(e.span.start as usize).column)
                }
                "file" => {
                    let f = self.map.get(self.file).name().replace('\\', "/");
                    format!("dz::str(\"{f}\", {})", f.len())
                }
                "function" => {
                    let n = self.current_fn.clone();
                    format!("dz::str(\"{n}\", {})", n.len())
                }
                _ => {
                    self.unsupported(e.span, "this intrinsic", "owed by M6");
                    "0".to_owned()
                }
            },
            ExprKind::If(_) | ExprKind::Block(_) | ExprKind::Switch(_) => {
                self.unsupported(e.span, "an `if`, block or `switch` used as a value", "owed by M5");
                "{}".to_owned()
            }
            ExprKind::With(_) | ExprKind::Catch { .. } | ExprKind::Try(_) => {
                self.unsupported(e.span, "`?T` / `!T` handling", "owed by M5");
                "{}".to_owned()
            }
            ExprKind::Range { .. } => {
                self.unsupported(e.span, "a range outside a `for` loop", "owed by M6");
                "{}".to_owned()
            }
            ExprKind::Tuple(_) => {
                self.unsupported(e.span, "a tuple value", "owed by M5");
                "{}".to_owned()
            }
            ExprKind::DotInfer { .. } => {
                self.unsupported(e.span, "an inferred `.Variant`", "owed by M5");
                "{}".to_owned()
            }
            ExprKind::MacroCall { .. } => {
                self.unsupported(e.span, "a macro invocation", "owed by M10");
                "{}".to_owned()
            }
            ExprKind::Error => "0".to_owned(),
        }
    }

    fn call(&mut self, callee: &Expr, args: &[Expr], span: Span) -> String {
        let rendered: Vec<String> = args.iter().map(|a| self.expr(a)).collect();

        // Builtins (spec §12.9, §9.8).
        if let ExprKind::Path(p) = &callee.kind {
            if p.segments.len() == 1 {
                let name = p.segments[0].name.name.as_str();
                match name {
                    "println" | "print" => {
                        return format!("dz::{name}({})", rendered.join(", "));
                    }
                    "panic" => {
                        let loc = self.source_location(span);
                        let msg = rendered.first().cloned().unwrap_or("\"\"".into());
                        return format!(
                            "dz::panic(reinterpret_cast<const char*>(({msg}).ptr), {loc})"
                        );
                    }
                    _ => {}
                }
                if dz_resolve::BUILTIN_FNS.contains(&name) {
                    self.unsupported(span, &format!("the builtin `{name}`"), "owed by M6");
                    return "0".to_owned();
                }
            }
        }

        let target = self.expr(callee);
        format!("{target}({})", rendered.join(", "))
    }

    fn struct_literal(&mut self, path: &Path, fields: &[FieldInit], span: Span) -> String {
        let ty = self.type_path(path, span);
        if fields.is_empty() {
            return format!("{ty}{{}}");
        }

        // C++20 designated initialisers read far better than the lambda below, but they
        // apply only to aggregates and must be written in declaration order.
        if self.standard >= 20 {
            if let Some(text) = self.designated_literal(&ty, path, fields, span) {
                return text;
            }
        }
        // C++17 has no designated initialisers, so build the value in a lambda. It costs
        // nothing after inlining and keeps field defaults working.
        let tmp = self.fresh("lit");
        let mut out = format!("[&] {{ {ty} {tmp}{{}}; ");
        let named = fields.iter().any(|f| f.name.is_some());
        for (i, f) in fields.iter().enumerate() {
            let v = self.expr(&f.value);
            match &f.name {
                Some(n) => {
                    let _ = write!(out, "{tmp}.{} = {v}; ", n.name);
                }
                None if !named => {
                    // Positional: field order is the declaration order (spec §7.3).
                    match self.nth_field_name(path, i, span) {
                        Some(n) => {
                            let _ = write!(out, "{tmp}.{n} = {v}; ");
                        }
                        None => {
                            self.unsupported(f.span, "this positional initialiser", "owed by M6");
                        }
                    }
                }
                None => {}
            }
        }
        let _ = write!(out, "return {tmp}; }}()");
        out
    }

    /// `Vec3{.x = 1, .y = 2}` — C++20 only, and only for a type with no constructor,
    /// since a type with one is not an aggregate.
    fn designated_literal(
        &mut self,
        ty: &str,
        path: &Path,
        fields: &[FieldInit],
        span: Span,
    ) -> Option<String> {
        let name = &path.segments.last()?.name.name;
        let sym = self.res.lookup_in_file(self.module, self.file, name)?;
        let symbol = self.res.symbol(sym);
        if symbol.members.iter().any(|m| m.sort == dz_resolve::MemberSort::Ctor) {
            return None;
        }
        let order: Vec<String> = symbol
            .members
            .iter()
            .filter(|m| m.sort == dz_resolve::MemberSort::Field)
            .map(|m| m.name.clone())
            .collect();

        // Pair each initialiser with the field it sets, positionally or by name.
        let mut pairs: Vec<(usize, String)> = Vec::new();
        for (i, f) in fields.iter().enumerate() {
            let field = match &f.name {
                Some(n) => order.iter().position(|x| *x == n.name)?,
                None => i,
            };
            if field >= order.len() {
                return None;
            }
            let value = self.expr(&f.value);
            pairs.push((field, value));
        }
        // Designated initialisers must appear in declaration order; Dazzle allows any.
        pairs.sort_by_key(|(i, _)| *i);

        let body: Vec<String> =
            pairs.iter().map(|(i, v)| format!(".{} = {v}", order[*i])).collect();
        let _ = span;
        Some(format!("{ty}{{ {} }}", body.join(", ")))
    }

    fn nth_field_name(&mut self, path: &Path, i: usize, _span: Span) -> Option<String> {
        let name = &path.segments.last()?.name.name;
        let sym = self.res.lookup_in_file(self.module, self.file, name)?;
        let s = self.res.symbol(sym);
        s.members
            .iter()
            .filter(|m| m.sort == dz_resolve::MemberSort::Field)
            .nth(i)
            .map(|m| m.name.clone())
    }

    fn value_path(&mut self, p: &Path, span: Span) -> String {
        let Some(first) = p.segments.first() else { return "0".into() };
        let name = first.name.name.as_str();

        // `module::thing`
        if p.segments.len() >= 2 {
            if let Some(target) = self.res.module_alias(self.file, name) {
                let rest: Vec<&str> =
                    p.segments[1..].iter().map(|s| s.name.name.as_str()).collect();
                return format!(
                    "{}::{}",
                    qualified_namespace(&self.ws.module(target).name),
                    rest.join("::")
                );
            }
        }

        // `Type::Variant`
        if p.segments.len() == 2 {
            if let Some(sym) = self.res.lookup_in_file(self.module, self.file, name) {
                if self.res.symbol(sym).kind == SymbolKind::Enum {
                    let owner = self.qualify(sym);
                    return format!("{owner}::{}", p.segments[1].name.name);
                }
            }
        }

        if p.segments.len() == 1 {
            // `self` is C++'s `this`, dereferenced so `.` works the same either way.
            if name == "self" {
                return "(*this)".to_owned();
            }
            if let Some(sym) = self.res.lookup_in_file(self.module, self.file, name) {
                return self.qualify(sym);
            }
            // A local, a parameter, or a field in scope inside a method (spec §7.3).
            return name.to_owned();
        }

        self.unsupported(span, "this path", "owed by M6");
        "0".to_owned()
    }

    fn qualify(&self, sym: SymbolId) -> String {
        let s = self.res.symbol(sym);
        if s.module == self.module {
            s.name.clone()
        } else {
            format!("{}::{}", qualified_namespace(&self.ws.module(s.module).name), s.name)
        }
    }
}

