/// `engine::render` → `dz::engine::render`.
fn qualified_namespace(module: &str) -> String {
    format!("dz::{module}")
}

fn namespace_open(module: &str) -> String {
    let mut s = String::from("namespace dz {\n");
    for part in module.split("::") {
        let _ = writeln!(s, "namespace {part} {{");
    }
    s
}

fn namespace_close(module: &str) -> String {
    let mut s = String::new();
    for part in module.split("::").collect::<Vec<_>>().into_iter().rev() {
        let _ = writeln!(s, "}}  // namespace {part}");
    }
    s.push_str("}  // namespace dz\n");
    s
}

fn file_stem(module: &str) -> String {
    module.replace("::", "_")
}

/// Strip separators and any type suffix, leaving something C++ accepts.
fn clean_number(text: &str) -> String {
    let cleaned: String = text.chars().filter(|c| *c != '_').collect();
    for suffix in
        ["usize", "isize", "i16", "i32", "i64", "u16", "u32", "u64", "f32", "f64", "i8", "u8"]
    {
        if let Some(stripped) = cleaned.strip_suffix(suffix) {
            if !stripped.is_empty() && !stripped.ends_with(['x', 'X', 'o', 'O', 'b', 'B']) {
                return stripped.to_owned();
            }
        }
    }
    if let Some(stripped) = cleaned.strip_suffix('f') {
        // `1.5f` is already a valid C++ float literal; `0xf` is a hex digit.
        if stripped.contains('.') || stripped.contains('e') {
            return cleaned;
        }
    }
    cleaned
}

/// Re-quote a Dazzle string body as a C++ string literal.
fn quote_cpp(body: &str) -> String {
    let mut out = String::from("\"");
    let mut chars = body.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                // `\0` in C++ inside a string can swallow following digits; be explicit.
                Some('0') => out.push_str("\\x00"),
                Some(other) => {
                    out.push('\\');
                    out.push(other);
                }
                None => out.push('\\'),
            }
        } else {
            out.push(c);
        }
    }
    out.push('"');
    out
}

/// Byte length of a string body after escape processing, for `dz::str`.
fn unescaped_len(body: &str) -> usize {
    let mut n = 0usize;
    let mut chars = body.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('x') => {
                    chars.next();
                    chars.next();
                    n += 1;
                }
                Some('u') => {
                    // `\u{...}`: count the encoded scalar, not the escape text.
                    let mut hex = String::new();
                    for h in chars.by_ref() {
                        if h == '}' {
                            break;
                        }
                        if h != '{' {
                            hex.push(h);
                        }
                    }
                    n += u32::from_str_radix(&hex, 16)
                        .ok()
                        .and_then(char::from_u32)
                        .map(|c| c.len_utf8())
                        .unwrap_or(1);
                }
                Some(_) => n += 1,
                None => n += 1,
            }
        } else {
            n += c.len_utf8();
        }
    }
    n
}

/// Order types so a struct is emitted after anything it stores by value.
fn sort_by_dependency(items: Vec<(FileId, &Item)>) -> Vec<(FileId, &Item)> {
    let index: HashMap<&str, usize> = items
        .iter()
        .enumerate()
        .filter_map(|(i, (_, it))| type_name(it).map(|n| (n, i)))
        .collect();

    let mut order: Vec<usize> = Vec::new();
    let mut state = vec![0u8; items.len()]; // 0 unvisited, 1 in progress, 2 done

    fn visit(
        i: usize,
        items: &[(FileId, &Item)],
        index: &HashMap<&str, usize>,
        state: &mut Vec<u8>,
        order: &mut Vec<usize>,
    ) {
        // A cycle means two structs contain each other by value, which cannot be laid
        // out; the type checker will have reported it, so just stop recursing.
        if state[i] != 0 {
            return;
        }
        state[i] = 1;
        if let ItemKind::Struct(s) = &items[i].1.kind {
            let mut seen = HashSet::new();
            for m in &s.members {
                if let MemberKind::Field(f) = &m.kind {
                    if let Some(name) = by_value_type_name(&f.ty) {
                        if seen.insert(name.to_owned()) {
                            if let Some(&dep) = index.get(name) {
                                visit(dep, items, index, state, order);
                            }
                        }
                    }
                }
            }
        }
        state[i] = 2;
        order.push(i);
    }

    for i in 0..items.len() {
        visit(i, &items, &index, &mut state, &mut order);
    }
    order.into_iter().map(|i| items[i]).collect()
}

fn type_name(item: &Item) -> Option<&str> {
    match &item.kind {
        ItemKind::Struct(s) => Some(&s.name.name),
        ItemKind::Enum(e) => Some(&e.name.name),
        _ => None,
    }
}

/// The named type a field stores **by value**; pointers and references do not force an
/// ordering because a forward declaration would do.
fn by_value_type_name(t: &Type) -> Option<&str> {
    match &t.kind {
        TypeKind::Path(p) => p.segments.last().map(|s| s.name.name.as_str()),
        TypeKind::Array { elem, .. } => by_value_type_name(elem),
        _ => None,
    }
}
