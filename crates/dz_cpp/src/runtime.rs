//! The generated runtime shim (spec §16.4).
//!
//! Emitted verbatim into every build. It depends on nothing but the C standard library,
//! has no allocator, no threading and no global constructors, and must compile clean under
//! `-std=c++17 -fno-exceptions -fno-rtti -Wall -Wextra` (§16.5).
//!
//! The small `template` helpers here are not a retreat from spec §8.6. That section argues
//! against mapping Dazzle's *generics* onto C++ templates, because C++ then re-checks them
//! once per instantiation, slowly and with bad errors. These are a handful of one-line
//! inline functions instantiated a few times each — the "C++ does this once per construct"
//! side of the same distinction.

pub const RUNTIME_H: &str = r##"// Generated by the Dazzle compiler. Do not edit.
// The Dazzle runtime shim (spec §16.4).
#ifndef DZ_RUNTIME_H
#define DZ_RUNTIME_H

#include <stdint.h>
#include <stddef.h>

// The access helpers below must vanish even in a debug build. A game has to stay playable
// at -O0, and without this each `xs[i]` costs three real function calls.
#if defined(_MSC_VER) && !defined(__clang__)
#define DZ_INLINE __forceinline
#else
#define DZ_INLINE inline __attribute__((always_inline))
#endif

namespace dz {

// --- source locations (spec §12.7) ----------------------------------------

struct SourceLocation {
    const char* file;
    const char* function;
    uint32_t line;
    uint32_t column;
};

// --- panics (spec §9.8) ---------------------------------------------------
//
// Never a C++ exception: the generated code builds with -fno-exceptions.

[[noreturn]] void panic(const char* message, SourceLocation where);
[[noreturn]] void panic_bounds(size_t index, size_t length, SourceLocation where);
void overflow(const char* op, SourceLocation where);

// --- strings and slices (spec §5.3) ---------------------------------------

struct str {
    const uint8_t* ptr;
    size_t len;

    constexpr str() : ptr(nullptr), len(0) {}
    // Not constexpr: `reinterpret_cast` is forbidden in a constant expression.
    str(const char* s, size_t n) : ptr(reinterpret_cast<const uint8_t*>(s)), len(n) {}
};

template <class T>
struct Slice {
    T* ptr;
    size_t len;

    constexpr Slice() : ptr(nullptr), len(0) {}
    constexpr Slice(T* p, size_t n) : ptr(p), len(n) {}

    DZ_INLINE T& operator[](size_t i) { return ptr[i]; }
    DZ_INLINE const T& operator[](size_t i) const { return ptr[i]; }

    T* begin() { return ptr; }
    T* end() { return ptr + len; }
    const T* begin() const { return ptr; }
    const T* end() const { return ptr + len; }
};

template <class T, size_t N>
struct Array {
    T data[N];

    DZ_INLINE T& operator[](size_t i) { return data[i]; }
    DZ_INLINE const T& operator[](size_t i) const { return data[i]; }
    constexpr size_t size() const { return N; }
    operator Slice<T>() { return Slice<T>(data, N); }

    T* begin() { return data; }
    T* end() { return data + N; }
    const T* begin() const { return data; }
    const T* end() const { return data + N; }
};

// --- optional and fallible (spec §9.3) ------------------------------------

struct Error {
    uint32_t code{};
    str message{};
    const SourceLocation* location{};
};

template <class T>
struct Opt {
    T value;
    bool has;

    constexpr Opt() : value(), has(false) {}
    // Not explicit: `return v` from a `?T` function is the success case (spec §9.1).
    Opt(T v) : value(v), has(true) {}
    static Opt some(T v) { return Opt(v); }
    static Opt none() { return Opt(); }
};

template <class T>
struct Res {
    T value;
    Error error;
    bool ok;

    constexpr Res() : value(), error(), ok(false) {}
    // Not explicit: `return v` and `return error(...)` pick the case (spec §9.1).
    Res(T v) : value(v), error(), ok(true) {}
    Res(Error e) : value(), error(e), ok(false) {}
    static Res good(T v) { return Res(v); }
    static Res bad(Error e) { return Res(e); }
};

// A `!void` still has to carry an error, so it gets a payload-free shape.
template <>
struct Res<void> {
    Error error;
    bool ok;

    constexpr Res() : error(), ok(false) {}
    static Res good() { Res r; r.ok = true; return r; }
    static Res bad(Error e) { Res r; r.error = e; r.ok = false; return r; }
};

// --- tuples (spec §5.4) ---------------------------------------------------

template <class... Ts> struct Tuple;
template <class A> struct Tuple<A> { A v0; };
template <class A, class B> struct Tuple<A, B> { A v0; B v1; };
template <class A, class B, class C> struct Tuple<A, B, C> { A v0; B v1; C v2; };
template <class A, class B, class C, class D>
struct Tuple<A, B, C, D> { A v0; B v1; C v2; D v3; };

// --- access helpers -------------------------------------------------------
//
// `.` in Dazzle reaches through pointers and references on its own (spec §5.2), and
// there is no `->`. `obj()` lets the generated code write a single form and leaves the
// pointer/value distinction to C++ overload resolution.

template <class T> DZ_INLINE T& obj(T& x) { return x; }
template <class T> DZ_INLINE const T& obj(const T& x) { return x; }
template <class T> DZ_INLINE T& obj(T* x) { return *x; }
template <class T> DZ_INLINE const T& obj(const T* x) { return *x; }

/// The result of `&x` / `&mut x`.
///
/// Dazzle's `&mut T` satisfies both `&mut T` and `^T` (spec §5.2), which in C++ are two
/// different types. Letting overload resolution pick the conversion keeps codegen from
/// needing the callee's parameter type.
template <class T>
struct Addr {
    T* p;
    // A `T&` already binds where a `const T&` is wanted, so two conversions suffice.
    DZ_INLINE operator T&() const { return *p; }
    DZ_INLINE operator T*() const { return p; }
};

template <class T> DZ_INLINE Addr<T> addr(T& x) { return Addr<T>{&x}; }

// Hand-rolled rather than pulled from <type_traits>, so the shim keeps its promise of
// depending on nothing but the C standard library. Compiler builtins are avoided too:
// `__is_pointer` exists in Clang but not in GCC.
template <class T> struct is_ptr { static constexpr bool value = false; };
template <class T> struct is_ptr<T*> { static constexpr bool value = true; };

/// `as` between numbers, pointers, and an enum and its backing type (spec §10.6).
///
/// `static_cast` already covers enum-to-integer and every numeric conversion; only
/// pointer-to-pointer needs `reinterpret_cast`.
template <class To, class From>
DZ_INLINE To cast(From f) {
    if constexpr (is_ptr<From>::value && is_ptr<To>::value) {
        return reinterpret_cast<To>(f);
    } else {
        return static_cast<To>(f);
    }
}

/// Bounds-checked index. Release builds define DZ_NO_BOUNDS_CHECK (spec §5.3).
template <class C>
DZ_INLINE auto index(C& c, size_t i, SourceLocation where) -> decltype(c[i]) {
#ifndef DZ_NO_BOUNDS_CHECK
    if (i >= c.len) { panic_bounds(i, c.len, where); }
#else
    (void)where;
#endif
    return c[i];
}

template <class T, size_t N>
DZ_INLINE T& index(Array<T, N>& a, size_t i, SourceLocation where) {
#ifndef DZ_NO_BOUNDS_CHECK
    if (i >= N) { panic_bounds(i, N, where); }
#else
    (void)where;
#endif
    return a.data[i];
}

/// Runs a block at scope exit, in reverse order of registration (spec §10.5).
template <class F>
struct Defer {
    F f;
    explicit Defer(F fn) : f(fn) {}
    ~Defer() { f(); }
    Defer(const Defer&) = delete;
    Defer& operator=(const Defer&) = delete;
};
template <class F> DZ_INLINE Defer<F> make_defer(F f) { return Defer<F>(f); }

}  // namespace dz

#endif  // DZ_RUNTIME_H
"##;

pub const RUNTIME_CPP: &str = r##"// Generated by the Dazzle compiler. Do not edit.
#include "dz_runtime.h"

#include <stdio.h>
#include <stdlib.h>

namespace dz {

/// Flush every stream before aborting. `abort()` does not, and losing the program's
/// output is the opposite of what someone reading a panic needs.
static void flush_all() {
    fflush(nullptr);
}

static void write_location(SourceLocation where) {
    fprintf(stderr, "  at %s (%s:%u:%u)\n", where.function, where.file, where.line,
            where.column);
}

void panic(const char* message, SourceLocation where) {
    fprintf(stderr, "panic: %s\n", message);
    write_location(where);
    flush_all();
    abort();
}

void panic_bounds(size_t index, size_t length, SourceLocation where) {
    fprintf(stderr, "panic: index %zu is out of bounds for length %zu\n", index, length);
    write_location(where);
    flush_all();
    abort();
}

void overflow(const char* op, SourceLocation where) {
    fprintf(stderr, "panic: %s overflowed\n", op);
    write_location(where);
    flush_all();
    abort();
}

}  // namespace dz
"##;

/// Temporary scaffolding: formatting and output.
///
/// Spec §16.4 is explicit that the shim performs no I/O beyond a panic message, and
/// §12.9 defines `println` as a compile-time-checked call lowering to `Format::format`.
/// Neither is buildable before the stdlib (M12), so this file stands in until then. It is
/// kept separate from the shim so that §16.4's contract is not quietly widened.
pub const PRELUDE_H: &str = r##"// Generated by the Dazzle compiler. Do not edit.
// TEMPORARY: stands in for the `Format` trait of spec §12.9 until the stdlib (M12).
#ifndef DZ_PRELUDE_H
#define DZ_PRELUDE_H

#include "dz_runtime.h"

#include <inttypes.h>
#include <stdio.h>

namespace dz {

inline void write_value(str s) { fwrite(s.ptr, 1, s.len, stdout); }
inline void write_value(const char* s) { fputs(s, stdout); }
inline void write_value(bool b) { fputs(b ? "true" : "false", stdout); }
inline void write_value(char32_t c) { printf("%lc", static_cast<wint_t>(c)); }
inline void write_value(float f) { printf("%g", static_cast<double>(f)); }
inline void write_value(double d) { printf("%g", d); }
inline void write_value(int8_t v) { printf("%" PRId8, v); }
inline void write_value(int16_t v) { printf("%" PRId16, v); }
inline void write_value(int32_t v) { printf("%" PRId32, v); }
inline void write_value(int64_t v) { printf("%" PRId64, v); }
inline void write_value(uint8_t v) { printf("%" PRIu8, v); }
inline void write_value(uint16_t v) { printf("%" PRIu16, v); }
inline void write_value(uint32_t v) { printf("%" PRIu32, v); }
inline void write_value(uint64_t v) { printf("%" PRIu64, v); }
template <class T> inline void write_value(T* p) { printf("%p", static_cast<void*>(p)); }

inline void write_format(str fmt) { write_value(fmt); }

/// Writes `fmt`, replacing each `{}` with the next argument.
template <class T, class... Rest>
inline void write_format(str fmt, T first, Rest... rest) {
    for (size_t i = 0; i < fmt.len; ++i) {
        if (i + 1 < fmt.len && fmt.ptr[i] == '{' && fmt.ptr[i + 1] == '}') {
            write_value(first);
            write_format(str(reinterpret_cast<const char*>(fmt.ptr + i + 2),
                             fmt.len - i - 2),
                         rest...);
            return;
        }
        fputc(static_cast<int>(fmt.ptr[i]), stdout);
    }
}

template <class... Ts> inline void print(str fmt, Ts... args) {
    write_format(fmt, args...);
}

template <class... Ts> inline void println(str fmt, Ts... args) {
    write_format(fmt, args...);
    fputc('\n', stdout);
}

}  // namespace dz

#endif  // DZ_PRELUDE_H
"##;
