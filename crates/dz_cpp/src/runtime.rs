pub const RUNTIME_CPP: &str = r##"// Generated by the Dazzle compiler. Do not edit.
#include "dz_runtime.h"

#include <stdio.h>
#include <stdlib.h>

namespace dz {

/// Flush every stream before aborting. `abort()` does not, and losing the program's
/// output is the opposite of what someone reading a panic needs.
static void flush_all() {
    fflush(nullptr);
}

static void write_location(SourceLocation where) {
    fprintf(stderr, "  at %s (%s:%u:%u)\n", where.function, where.file, where.line,
            where.column);
}

void panic(const char* message, SourceLocation where) {
    fprintf(stderr, "panic: %s\n", message);
    write_location(where);
    flush_all();
    abort();
}

void panic_bounds(size_t index, size_t length, SourceLocation where) {
    fprintf(stderr, "panic: index %zu is out of bounds for length %zu\n", index, length);
    write_location(where);
    flush_all();
    abort();
}

/// `panic("…")` takes a `str`, which is a pointer and a length rather than a
/// NUL-terminated string, so it cannot go through `panic` above.
void panic_len(const uint8_t* message, size_t len, SourceLocation where) {
    fputs("panic: ", stderr);
    fwrite(message, 1, len, stderr);
    fputc('\n', stderr);
    write_location(where);
    flush_all();
    abort();
}

void unreachable(SourceLocation where) {
    fputs("panic: reached code the compiler proved unreachable\n", stderr);
    write_location(where);
    flush_all();
    abort();
}

void overflow(const char* op, SourceLocation where) {
    fprintf(stderr, "panic: %s overflowed\n", op);
    write_location(where);
    flush_all();
    abort();
}

}  // namespace dz
"##;

/// Temporary scaffolding: formatting and output.
///
/// Spec §16.4 is explicit that the shim performs no I/O beyond a panic message, and
/// §12.9 defines `println` as a compile-time-checked call lowering to `Format::format`.
/// Neither is buildable before the stdlib (M12), so this file stands in until then. It is
/// kept separate from the shim so that §16.4's contract is not quietly widened.
pub const PRELUDE_H: &str = r##"// Generated by the Dazzle compiler. Do not edit.
// TEMPORARY: stands in for the `Format` trait of spec §12.9 until the stdlib (M12).
#ifndef DZ_PRELUDE_H
#define DZ_PRELUDE_H

#include "dz_runtime.h"

#include <inttypes.h>
#include <stdio.h>
#include <wchar.h>

namespace dz {

// Formatting is written against a *sink* rather than against stdout, because `error(...)`
// and `format(...)` need the same `{}` substitution writing somewhere other than the
// console (spec §9.1, §12.9).

struct StdoutSink {
    void write(const char* p, size_t n) { fwrite(p, 1, n, stdout); }
    void put(char c) { fputc(static_cast<int>(c), stdout); }
};

/// Writes into a fixed buffer and stops at its end. Truncation is silent and deliberate:
/// an error message is diagnostic text, and failing to build one must never itself fail.
struct BufSink {
    char* buf;
    size_t cap;
    size_t n;

    void write(const char* p, size_t k) {
        for (size_t i = 0; i < k; ++i) { put(p[i]); }
    }
    void put(char c) {
        if (n + 1 < cap) { buf[n++] = c; }
    }
};

template <class S> inline void write_value(S& s, str v) {
    s.write(reinterpret_cast<const char*>(v.ptr), v.len);
}
template <class S> inline void write_value(S& s, const char* v) {
    for (const char* p = v; *p; ++p) { s.put(*p); }
}
template <class S> inline void write_value(S& s, bool v) {
    write_value(s, v ? "true" : "false");
}

/// Numbers go through `snprintf` into a small stack buffer, so one code path serves both
/// sinks and neither of them has to know how to render a `double`.
template <class S, class... Ts>
inline void write_printf(S& s, const char* spec, Ts... args) {
    char tmp[64];
    int k = snprintf(tmp, sizeof(tmp), spec, args...);
    if (k > 0) { s.write(tmp, static_cast<size_t>(k) < sizeof(tmp) ? static_cast<size_t>(k)
                                                                   : sizeof(tmp) - 1); }
}

template <class S> inline void write_value(S& s, char32_t v) {
    write_printf(s, "%lc", static_cast<wint_t>(v));
}
template <class S> inline void write_value(S& s, float v) {
    write_printf(s, "%g", static_cast<double>(v));
}
template <class S> inline void write_value(S& s, double v) { write_printf(s, "%g", v); }
template <class S> inline void write_value(S& s, int8_t v) { write_printf(s, "%" PRId8, v); }
template <class S> inline void write_value(S& s, int16_t v) { write_printf(s, "%" PRId16, v); }
template <class S> inline void write_value(S& s, int32_t v) { write_printf(s, "%" PRId32, v); }
template <class S> inline void write_value(S& s, int64_t v) { write_printf(s, "%" PRId64, v); }
template <class S> inline void write_value(S& s, uint8_t v) { write_printf(s, "%" PRIu8, v); }
template <class S> inline void write_value(S& s, uint16_t v) { write_printf(s, "%" PRIu16, v); }
template <class S> inline void write_value(S& s, uint32_t v) { write_printf(s, "%" PRIu32, v); }
template <class S> inline void write_value(S& s, uint64_t v) { write_printf(s, "%" PRIu64, v); }
template <class S, class T> inline void write_value(S& s, T* p) {
    write_printf(s, "%p", static_cast<void*>(p));
}

template <class S> inline void write_format(S& s, str fmt) { write_value(s, fmt); }

/// Writes `fmt`, replacing each `{}` with the next argument.
template <class S, class T, class... Rest>
inline void write_format(S& s, str fmt, T first, Rest... rest) {
    for (size_t i = 0; i < fmt.len; ++i) {
        if (i + 1 < fmt.len && fmt.ptr[i] == '{' && fmt.ptr[i + 1] == '}') {
            write_value(s, first);
            write_format(s, str(fmt.ptr + i + 2, fmt.len - i - 2), rest...);
            return;
        }
        s.put(static_cast<char>(fmt.ptr[i]));
    }
}

template <class... Ts> inline void print(str fmt, Ts... args) {
    StdoutSink s;
    write_format(s, fmt, args...);
}

template <class... Ts> inline void println(str fmt, Ts... args) {
    StdoutSink s;
    write_format(s, fmt, args...);
    fputc('\n', stdout);
}

/// Storage for formatted messages. Owed by M12: a real answer needs the stdlib's `String`.
/// Spec §9.2 requires that `error(...)` never allocates
/// and that the message outlive the call that built it; a small ring of static buffers is
/// the cheapest thing that does both. It is not unbounded — the fifth live message
/// overwrites the first — which is the trade this makes explicit rather than hiding.
inline char* message_buffer() {
    static char buffers[4][256];
    static unsigned next = 0;
    return buffers[next++ % 4];
}

template <class... Ts> inline str format(str fmt, Ts... args) {
    BufSink s{message_buffer(), 256, 0};
    write_format(s, fmt, args...);
    return str(s.buf, s.n);
}

/// `error(code, "…", args…)` (spec §9.1). The location is copied into static storage so
/// the `^SourceLocation` an `Error` carries is never dangling.
inline const SourceLocation* intern_location(SourceLocation where) {
    static SourceLocation slots[8];
    static unsigned next = 0;
    SourceLocation* p = &slots[next++ % 8];
    *p = where;
    return p;
}

template <class... Ts>
inline Error make_error(uint32_t code, SourceLocation where, str fmt, Ts... args) {
    Error e;
    e.code = code;
    e.message = format(fmt, args...);
    e.location = intern_location(where);
    return e;
}

}  // namespace dz

#endif  // DZ_PRELUDE_H
"##;
