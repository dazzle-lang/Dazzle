//! The generated runtime shim (spec §16.4).
//!
//! Emitted verbatim into every build. It has no allocator, no threading and no global
//! constructors, and must compile clean under `-std=c++17 -fno-exceptions -fno-rtti -Wall
//! -Wextra` (§16.5). Its only includes are the C standard library and `<new>` — spec §6.6
//! lowers copy assignment to "destroy, put back at defaults, then copy", and the middle
//! step has no spelling other than placement new.
//!
//! The small `template` helpers here are not a retreat from spec §8.6. That section argues
//! against mapping Dazzle's *generics* onto C++ templates, because C++ then re-checks them
//! once per instantiation, slowly and with bad errors. These are a handful of one-line
//! inline functions instantiated a few times each — the "C++ does this once per construct"
//! side of the same distinction.

