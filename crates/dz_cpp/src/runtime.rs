// friends, because the fixed-width names are aliases and which fundamental type each one
// aliases differs per platform. On macOS `size_t` is `unsigned long` while `uint64_t` is
// `unsigned long long`, so an overload set written with the fixed-width names does not
// cover `size_t` at all: every candidate needs a conversion, and the call is ambiguous.
// `xs.len` is a `usize`, so that was every `println("{}", xs.len)` on macOS, back when
